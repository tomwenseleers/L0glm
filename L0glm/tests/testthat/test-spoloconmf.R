spolo_test_data <- function() {
  set.seed(12)
  n <- 180L
  X <- convmatrix(convkernel("gaussian", 15L, list(sigma = 1.5)), n)
  H <- cbind(X[, c(25, 70, 135)], pmax(0, 1 - abs(seq_len(n) - 100) / 15))
  H <- H %*% Matrix::Diagonal(x = 1 / Matrix::colSums(H))
  S <- matrix(rexp(24, rate = 1 / 3000), 4, 6)
  B <- splines::bs(seq_len(n), df = 4, intercept = TRUE)
  mu <- as.matrix(H %*% S) + B %*% matrix(20, 4, 6)
  list(X = X, Y = matrix(rpois(length(mu), mu), n, 6), B = B)
}

test_that("Poisson factorization preserves shapes, channels and the complete objective", {
  d <- spolo_test_data()
  fit <- spoloconmf(d$X, cbind(d$Y, silent = 0), background = d$B, ncores = 1L)
  expect_s3_class(fit, "spoloconmf")
  expect_s4_class(fit$H, "dgCMatrix")
  expect_equal(ncol(fit$S), 7L)
  expect_true(all(fit$S[, 7L] == 0))
  expect_equal(unname(fitted(fit)), unname(as.matrix(fit$H %*% fit$S) + d$B %*% fit$alpha), tolerance = 1e-8)
  expect_true(all(fit$S >= 0) && all(fit$alpha >= 0))
  expect_equal(as.numeric(Matrix::colSums(fit$H)), rep(1, ncol(fit$H)), tolerance = 1e-10)
  for (j in seq_len(ncol(fit$H))) {
    h <- as.numeric(fit$H[, j]); rows <- which(h > 0)
    expect_true(all(diff(rows) == 1L))
    expect_true(all(diff(log(h[rows]), differences = 2L) <= 1e-6))
  }
  expect_true(all(fit$history$delta[fit$history$accepted] <= 1e-6))
  expect_equal(sum(fit$history$delta[fit$history$accepted]), fit$diagnostics$complete_delta, tolerance = 1e-6)
  expect_equal(fit$objective$IC_compounds, -2 * fit$objective$loglik +
    fit$objective$lambda_rank * ncol(fit$H))
  expect_identical(fit$diagnostics$fitting_calls_in_clustering, 0L)
  expect_output(print(fit), "Sparse Poisson log-concave NMF")
})

test_that("dense and sparse starts, penalty scales and OpenMP give the same result", {
  d <- spolo_test_data()
  a <- spoloconmf(d$X, d$Y, d$B, ncores = 1L)
  b <- spoloconmf(as.matrix(d$X), d$Y, d$B, lambda = a$objective$lambda_rank, ncores = 2L)
  expect_equal(as.matrix(a$H), as.matrix(b$H), tolerance = 1e-6)
  expect_equal(a$S, b$S, tolerance = 1e-5)
  expect_equal(a$mu, b$mu, tolerance = 1e-6)
  expect_equal(a$objective$IC_compounds, b$objective$IC_compounds, tolerance = 1e-7)
  native <- getFromNamespace("spolo_spectral_cpp", "L0glm")
  x <- matrix(c(.1, .2, .4, .2, .1), ncol = 1)
  y <- cbind(c(0, 2, 5, 3, 0), 0)
  mu <- x %*% matrix(c(6, 0), 1)
  dense <- native(y, mu, x, matrix(c(6, 0), 2), 3L, 1L)
  sparse <- native(y, mu, Matrix::Matrix(x, sparse = TRUE), matrix(c(6, 0), 2), 3L, 2L)
  expect_identical(dense, sparse)
  expect_true(dense$change <= 0)
})

test_that("empty selections and invalid inputs are handled explicitly", {
  X <- convmatrix(convkernel("gaussian", 9L), 25L)
  fit <- spoloconmf(X, matrix(0, 25, 2), ncores = 1L)
  expect_equal(dim(fit$H), c(25L, 0L))
  expect_equal(dim(fit$S), c(0L, 2L))
  expect_true(all(fitted(fit) == 0))
  expect_true(is.finite(fit$objective$IC_compounds))
  expect_error(spoloconmf(X, matrix(.5, 25, 2)), "counts")
  expect_error(spoloconmf(X, matrix(0, 24, 2)), "nrow")
  expect_error(spoloconmf(X, rep(0, 25), background = rep(-1, 25)), "background")
  expect_error(spoloconmf(X, rep(0, 25), control = list(unknown = 1)), "Unknown")
  bad <- matrix(c(1, 0, 1), 3, 1)
  expect_error(spoloconmf(bad, rep(0, 3)), "contiguous")
})
