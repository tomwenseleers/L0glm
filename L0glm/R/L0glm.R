#' to a multivariate response scenario, with each column representing a different response.
#' @param family
#' a description of the error distribution and link function to be
#' used in the model. This should be a call to a family function. (See
#' \code{stats::family} for details of family functions.)
#' @param weights 
#' A vector of observation weights ("prior weights") of length \code{n}, 
#' or a matrix of weights with dimension \code{c(n, m)}, with \code{n} corresponding to 
#' the number of observations and \code{m} to the number of columns in \code{y}.
#' @param start
#' A vector of starting values for the coefficients to estimate of length \code{p}, 
#' or a matrix of starting values with dimension \code{c(p, m)}, 
#' with \code{p} corresponding to the number of predictors and \code{m} 
#' to the number of columns in \code{y}.
#' @param offset 
#' An optional vector of offset values of length \code{p}, or a matrix of offset values
#' with dimensions \code{c(p, m)}. The offset is a known quantity that is 
#' included in the linear predictor of the model. If specified, the offset is 
#' included in the calculation of the linear predictor and the 
#' working response.
#' @param lambda
#' either a scalar, a vector of numerics, or a character. Set \code{lambda = 0} 
#' to disable penalization.
#' @param no.pen
#' a vector of coefficient indices (including the intercept if applicable) that should 
#' \strong{not} be penalized.
#' @param nonnegative
#' a logical indicating whether nonnegativity constraints should be applied.
#' @param normalize
#' should the covariate matrix be normalized with the L2 norm (Euclidean norm)?
#' It is advised to use normalization unless the covariates were measured on a
#' similar unit scale.
#' @param solver
#' solver used for optimization (see details). It should be one of \code{"osqp"},
#' \code{"glmnet"}, \code{"eigen"}, \code{"nnls"}.
#' @param method
#' method used for the eigen solver (see details). It should be an integer from 
#' 1 to 8.
#' @param lower
#' lower limit for box constraints. It should be an integer, a vector of length 
#' \code{p} or a matrix with dimensions \code{c(p, m)}.
#' @param upper
#' upper limit for box constraints. It should be an integer, a vector of length 
#' \code{p} or a matrix with dimensions \code{c(p, m)}.
#' @param parallelize
#' a logical value indicating whether the columns of the response matrix \code{y} 
#' should be fitted in parallel in the multivariate case. If \code{TRUE}, each 
#' column of \code{y} is fitted concurrently, potentially speeding up computation.
#' If \code{FALSE}, the columns are fitted sequentially. Note that parallelization 
#' requires sufficient computational resources (multiple cores) to be effective.
#' @param maxit 
#' maximum number of IRLS iterations
#' @param grouped
#' a logical value indicating whether a grouped fit should be performed in the
#' multivariate case. 
#' If \code{TRUE}, the algorithm will perform a group fitting procedure where 
#' the columns of the response matrix \code{y} are refitted for a maximum number 
#' of iterations specified by \code{group.maxit}. The starting value for each 
#' iteration is the average of all columns of \code{y}. This can improve model 
#' fit by incorporating information from all responses into the fitting process.
#' @param group.maxit
#' an integer value specifying the maximum number of iterations for the group 
#' fitting procedure when \code{grouped = TRUE}. This determines how many times
#' the columns of the response matrix \code{y} will be refitted using the average 
#' of all columns of \code{y} as the starting value. 
#' @param relaxed
#' a logical value indicating whether an additional refinement fit should be 
#' performed at the end of the algorithm with \code{lambda = 0}. If \code{TRUE},
#' the algorithm will conduct a final fit using a nonnegative Poisson GLM, starting
#' with 1/ average coefficients over responses from the previous fit and only 
#' including variables selected earlier via the iterated L0 GLMs. This approach
#' can help to fine-tune the final model estimates. 
#' @param warm.start 
#' a numeric value in the range of [0, 1] that represents the level of confidence 
#' in the initial start values. This parameter is used in a weighted average to 
#' calculate the 'start' value. 
#' The formula used is: 
#' \deqn{start = warm.start*start + (1-warm.start)*rep(sd(start)^(1/gamma), ncol(X))}
#' If `warm.start` is closer to 1, more weight is given to the original 'start' value.
#' @param prior.mean
#' a numeric value specifying the center for nonzero centered ridge regularization. 
#' If \code{prior.mean} is not specified, the algorithm will perform the default 
#' zero centered Ridge Regression.
#' It should be a vector of length \code{p}.
#' @param warmupiters
#' an integer specifying the number of warm-up iterations before weights are updated in the 
#' IRLS algorithm. 
#' @param gamma
#' the exponent used for computing the adaptive ridge penalty weights. It is
#' recommended to work with \code{gamma = 2} (Frommlet et Nuel 2016).
#' @param thresh
#' a threshold under which the fitted coefficients are clipped to 0.
#' @param tol
#' stop iteration when the difference in coefficients between iterations is
#' smaller than this threshold. The coefficient difference is defined as:
#' \eqn{\frac{\|coefs^{(k-1)} - coefs^{(k)}}{\|coefs^{(k-1)}\|}}
#' @param control.solver
#' list of parameters controlling the optimization solvers. Should be NULL 
#' (which will be filledwith defaults, check \code{\link{control.solver.gen}} for
#' more details) or generated sing the \code{\link{control.solver.gen}} function. 
#' The specific parameters required and their roles depend on the solver in use. 
#' Refer to the documentation in \code{\link{control.solver.gen}} or specific 
#' solver functions (\code{"osqp"}, \code{"glmnet"}, \code{"eigen"} and \code{"nnls"})
#' for more details on the available parameters.
#' @param IC
#' threshold tuning criterion. It should be one of \code{"aic"}, 
#' \code{"bic"}, \code{"gic"}, \code{"ebic"}, \code{"mbic"}.
#' Threshold tuning is performed using TODO add chosen optimization function 
#' @param verbose
#' print algorithm progression to console?
#'
#' @details
#' 
#' \strong{Structure of the algorithm}
#' If the provided data is multivariate, algorithm parallellizes the columns of
#' \code{y} if \code{parallellize == TRUE}. Otherwise, these are fit sequentially.
#' \code{\link{L0glm.internal}} is called for every column of \code{y}. If
#' \code{grouped == TRUE}, all of the columns are refitted \code{group.maxit} times, 
#' using the average of all the columns fitted on the previous iteration and only 
#' refitting the selected coefficients in the previous iterations. 
#' If \code{y} is a vector or a matrix of \code{ncol(y) == 1}, the data is fit once.
#' If \code{relaxed == TRUE}, the algorithm performs a final fit using a nonnegative 
#' Poisson GLM, starting with 1/average coefficients over responses from the 
#' previous fit and only including variables selected earlier via the iterated L0 GLMs. 
#' This approach can help to fine-tune the final model estimates. 
#' 
#' \code{\link{L0glm.fit.internal}} follows these steps:
#' 1. It first normalizes the columns of X if 'normalize' is TRUE. Then it checks 
#' if the 'family' parameter is a valid family object and assigns the family 
#' functions accordingly.
#' 2. It initializes the 'mu' and 'eta' variables, either with the provided 
#' 'start' values or with constant starting values.
#' 3. Then, the function enters a loop for a maximum of 'maxit' iterations. In 
#' each iteration:
#' \itemize{
#' \item{It computes the working responses 'z' and the weights 'W'.}
#' \item{It updates the ridge penalties based on the current 'beta' coefficients.}
#' \item{It fits a weighted least squares model with ridge regularization, updating 
#'      the 'beta' coefficients.}
#' \item{It then zeros out any 'beta' coefficients below the 'thresh' threshold, 
#'      and updates 'nonzero', 'eta', 'mu', and 'dev'.}}
#' 4. The loop continues until the relative change in 'beta' is below the 'tol' threshold.
#' 5. Finally, the function returns a list containing the estimated 'beta' coefficients, the observation weights,
#'    the penalty weights, the ridge penalties, and the working responses.
#'
#'
#' @return
#' \code{L0glm.fit} returns a list containing the following elements:
#' \item{\code{coefficients}}{a vector or matrix of fitted coefficients.}
#' \item{\code{weights}}{a vector or matrix of observation weights.}
#' \item{\code{init.lambda}}{intial lambda.}
#' \item{\code{lambdas}}{a vector or matrix with the adaptive penalties lambdas.}
#' \item{\code{family}}{The error structure used to fit the data.}
#' \item{\code{z}}{a vector or matrix containing the working response in the 
#' final iteration of code{\link{L0glm.fit}}.}
#' \item{\code{X}}{X matrix.}
#' \item{\code{y}}{y vector or matrix.}
#'
#'
#' @export
L0glm.fit = function(X, 
                     y, 
                     family = gaussian(identity),
                     weights = NULL,
                     start = NULL,
                     offset = NULL,
                     lambda = 1,
                     no.pen = 0, # Vector of unpenalized indices. Include intercept if not to be penalized.
                     nonnegative = FALSE,
                     normalize = FALSE,
                     solver = "eigen", 
                     method = 7L,
                     lower = rep(-.Machine$double.xmax, ncol(X)),
                     upper = rep(.Machine$double.xmax, ncol(X)),
                     parallellize = TRUE,
                     maxit = 25,
                     grouped = TRUE, # TODO: bit unclear what this one does in combination with relaxed, maybe single argument group_penalty="independent", "relaxed independent", "group" or "relaxed group" might be clearer?
                     group.maxit = 6, 
                     relaxed = TRUE,
                     warm.start = 0.9,
                     prior.mean = NULL, # Should be a vector of length ncol(X). 
                     warmupiters = 1, # TODO: go back to ifelse(family$family == "gaussian", 1, 4)?
                     gamma = 2,
                     thresh = 1e-5, 
                     tol = 1E-10,
                     control.solver = do.call("control.solver.gen", list(solver = solver, method = method)),
                     IC = "gic",
                     verbose = FALSE){
  require(parallel)
  require(qlcMatrix)
  # TODO if lambda is NULL and starting values are passed, calculate lambda from starting values
  y = as.matrix(y)
  if (issparse(X)) { X = as(Matrix(X, sparse = TRUE), "dgCMatrix") } else { X = Matrix(X, sparse = FALSE) }
  no.pen.start <- no.pen
  init.lambda <- lambda
  # Make weights, offset and start into a matrix if they are provided as a vector and y is multichannel.
  if(!is.null(weights)){
    if(ncol(y) > 1 & ncol(as.matrix(weights)) == 1){
      weights = matrix(rep(weights, times = ncol(y)), nrow = length(weights), ncol = ncol(y))
    }
  } else { # If no weights are passed
    if(ncol(y) > 1){ # Multichannel
      weights = matrix(1, nrow = nrow(y), ncol = ncol(y))
    } else { # Single channel
      weights = rep(1, nrow(X))
    }
  }
  
  if(!is.null(offset)){
    if(ncol(y) > 1 & ncol(as.matrix(offset)) == 1){
      offset <- matrix(rep(offset, times = ncol(y)), nrow = length(offset), ncol = ncol(y))
    }
  } else { # If no offset is passed
    if(ncol(y) > 1){ # Multichannel
      offset <- Matrix(0, nrow = nrow(X), ncol=ncol(y), sparse=T)
    } else { # Single channel
      offset = rep(0, nrow(X))
    }
  }
  
  if(!is.null(start)){
    if(ncol(y) > 1 & ncol(as.matrix(start)) == 1){
      start <- matrix(rep(start, times = ncol(y)), nrow = length(start), ncol = ncol(y))
    } else if(nrow(as.matrix(start)) != ncol(X) | ncol(as.matrix(start)) != ncol(y)){ # nrow(as.matrix(start)) != )
      stop("Start needs to be of dimensions ncol(X), ncol(y).")
    } 
    if(normalize == TRUE){
      Xscaled = normalizeX(X)
      scaling = attr(Xscaled, "scaling")
      start = start*scaling
    }
    start = warm.start*start + (1-warm.start)*rep(sd(start)^(1/gamma), ncol(X))
  } else {
    start <- matrix(0, nrow = ncol(X), ncol = ncol(y)) # passing all zero start values is interpreted as NULL & will result in proper initialisation later on # matrix(sqrt(3), nrow = ncol(X), ncol = ncol(y)) # corresponding in Bayesian sense to assuming initial Gaussian prior with SD of 3, which is the most commonly chosen prior (lambda=1/start^2 and lambda=1/SD prior^2)
  }
  
  if(nonnegative) lower[lower < 0] <- 0
  if(ncol(y) > 1){
    if(!grouped) group.maxit <- 1 # Set group max iteration to 1 if group selection is negative -> channels will be fit independently
    # Define the number of cores to use (if it is 1, don't parallellize)
    n_cores <- round(detectCores()/2) 
    
    if(parallellize & n_cores > 1){
      # Determine the type of cluster based on the operating system
      cluster_type <- if (Sys.info()["sysname"] == "Windows") "PSOCK" else "FORK"
      
      # Create a cluster using the number of cores
      cl <- makeCluster(n_cores, type = cluster_type) # on Mac & Ubuntu type="FORK" is faster
      
      # Export the functions to the workers
      clusterExport(cl, list("fun", "L0glm.fit.internal"))
      
      # Load the required libraries and functions on each worker
      # (this only needs to be done once)
      cleval <- clusterEvalQ(cl, {
        require(L0glm)
        devtools::load_all(".") # TODO remove this? this should not be necessary once all callable functions are correctly exported by the L0glm package
      })
      
      # Create the chunks for parallellization
      cols <- 1:ncol(y)
      chunk.size <- length(cols) %/% n_cores
      extra <- length(cols) %% n_cores
      chunk_sizes <- rep(chunk.size, n_cores)
      if(extra > 0) {
        chunk_sizes[1:extra] <- chunk_sizes[1:extra] + 1
      }
      
      split_points <- c(0, cumsum(chunk_sizes))
      split_vector <- rep(1:n_cores, chunk_sizes)
      chunks <- split(cols, split_vector)
      
      
      for(i in 1L:group.maxit){
        # print(i)
        if(i > 1){
          avgcoefs = rowMeans(coefficients)
          variable.indices = which(avgcoefs > 0)
          no.pen.new.indices <- no.pen.start[no.pen.start %in% variable.indices] # Recalculate no.pen indices
          no.pen <- match(no.pen.new.indices, variable.indices)
          start <- matrix(rep(avgcoefs, times = ncol(y)), nrow = length(avgcoefs), ncol = ncol(y))
        } else {
          variable.indices <- 1:ncol(X)
        }
        coefficients <- lambdas.mat <- Matrix(0, nrow = ncol(X), ncol = ncol(y), sparse = TRUE)
        weights.mat <- Matrix(0, nrow = nrow(X), ncol = ncol(y), sparse = TRUE)
        
        if(length(variable.indices) == 0) {
          break
          if(verbose) warning("Zero coefficients produced. Try using a lower lambda.")
        } else if (length(variable.indices) == 1) { # If only 1 variable selected => don't parallelize
          fit <- do.call(cbind, lapply(1:ncol(y), function(col) {
            L0glm.fit.internal(X = X[,variable.indices,drop=F],
                               y = y[,col,drop=F],
                               family=family,
                               lambda = lambda,
                               gamma = gamma,
                               nonnegative = nonnegative,
                               normalize = normalize,
                               offset = as.vector(offset[col, drop = F]),
                               weights = as.vector(weights[,col,drop=F]),
                               warm.start = warm.start,
                               prior.mean = prior.mean[variable.indices],
                               start = as.vector(start[variable.indices, col, drop = F]),
                               lower = lower[variable.indices],
                               upper = upper[variable.indices],
                               maxit = maxit,
                               thresh = thresh,
                               solver = solver,
                               method = method,
                               tol = tol,
                               no.pen = no.pen,
                               control.solver = control.solver,
                               warmupiters = warmupiters,
                               verbose = verbose)
          }))
          coefficients[variable.indices,] <-  Matrix(do.call(cbind, fit[1, ]), sparse = TRUE)
          weights.mat <-  Matrix(do.call(cbind, fit[2, ]), sparse = TRUE)
          # pen.weights.mat[variable.indices,] <-  Matrix(do.call(cbind, fit[3, ]), sparse = TRUE)
          lambdas.mat[variable.indices,] <-  Matrix(do.call(cbind, fit[3, ]), sparse = TRUE)
          z.mat <-  Matrix(do.call(cbind, fit[4, ]), sparse = TRUE)
          
        } else { # If length(variable.indices) > 1 (more than 1 variable selected)
          fit <- clusterApply(cl, chunks, fun,
                              X = X[,variable.indices, drop = F], 
                              y = y, 
                              family = family, 
                              lambda = lambda, 
                              gamma = gamma,
                              maxit = maxit,
                              tol = tol,
                              no.pen = no.pen,
                              thresh = thresh, 
                              solver = solver, 
                              warm.start = warm.start,
                              prior.mean = prior.mean[variable.indices],
                              weights = weights, 
                              start = start[variable.indices, , drop = F], 
                              lower = lower[variable.indices], 
                              upper = upper[variable.indices], 
                              offset = offset,
                              method = method, 
                              nonnegative = nonnegative, 
                              normalize = normalize,
                              control.solver = control.solver, 
                              warmupiters = warmupiters, 
                              verbose = verbose)
          
          # Extract results
          coefficients[variable.indices,] <- do.call(cbind, lapply(fit, function(x) sapply(x, function(y) y$coefficients)))
          weights.mat <- do.call(cbind, lapply(fit, function(x) sapply(x, function(y) y$weights)))
          # pen.weights.mat[variable.indices,] <- do.call(cbind, lapply(fit, function(x) sapply(x, function(y) y$pen.weights)))
          lambdas.mat[variable.indices,] <- do.call(cbind, lapply(fit, function(x) sapply(x, function(y) y$lambdas)))
          z.mat <- do.call(cbind, lapply(fit, function(x) sapply(x, function(y) y$z)))
        }
      }
      
      if(relaxed){
        # Apply relaxed group L0 feature selection
        avgcoefs = rowMeans(coefficients)
        variable.indices = which(avgcoefs != 0)
        no.pen.new.indices <- no.pen.start[no.pen.start %in% variable.indices] # Recalculate no.pen indices
        no.pen <- match(no.pen.new.indices, variable.indices)
        
        if(length(variable.indices) > 1){
          start <- matrix(rep(avgcoefs, times = ncol(y)), nrow = length(avgcoefs), ncol = ncol(y))
          coefficients <- lambdas.mat <- Matrix(0, nrow = ncol(X), ncol = ncol(y), sparse = TRUE)
          weights.mat <- Matrix(0, nrow = nrow(X), ncol = ncol(y), sparse = TRUE)
          
          fit <- clusterApply(cl, chunks, fun,
                              X = X[,variable.indices, drop = F], 
                              y = y, 
                              family = family, 
                              lambda = 1e-30, 
                              gamma = gamma,
                              maxit = maxit,
                              tol = tol,
                              no.pen = no.pen,
                              thresh = thresh, 
                              solver = solver, 
                              warm.start = warm.start,
                              prior.mean = prior.mean[variable.indices],
                              weights = weights, 
                              start = start[variable.indices, , drop = F], 
                              lower = lower[variable.indices], 
                              upper = upper[variable.indices], 
                              offset = offset,
                              method = method, 
                              nonnegative = nonnegative, 
                              normalize = normalize,
                              control.solver = control.solver, 
                              warmupiters = warmupiters, 
                              verbose = verbose)
          # Extract results
          coefficients[variable.indices,] <- do.call(cbind, lapply(fit, function(x) sapply(x, function(y) y$coefficients)))
          weights.mat <- do.call(cbind, lapply(fit, function(x) sapply(x, function(y) y$weights)))
          # pen.weights.mat[variable.indices,] <- do.call(cbind, lapply(fit, function(x) sapply(x, function(y) y$pen.weights)))
          lambdas.mat[variable.indices,] <- do.call(cbind, lapply(fit, function(x) sapply(x, function(y) y$lambdas)))
          z.mat <- do.call(cbind, lapply(fit, function(x) sapply(x, function(y) y$z)))
          
        } else if (length(variable.indices) == 1){
          fit <- do.call(cbind, lapply(1:ncol(y), function(col) {
            L0glm.fit.internal(X = X[,variable.indices,drop=F],
                               y = y[,col,drop=F],
                               family=family,
                               lambda = lambda,
                               gamma = gamma,
                               nonnegative = nonnegative,
                               normalize = normalize,
                               offset = as.vector(offset[col, drop = F]),
                               weights = as.vector(weights[,col,drop=F]),
                               warm.start = warm.start,
                               prior.mean = prior.mean[variable.indices],
                               start = as.vector(start[variable.indices, col, drop = F]),
                               lower = lower[variable.indices],
                               upper = upper[variable.indices],
                               maxit = maxit,
                               thresh = thresh,
                               solver = solver,  
                               method = method,  
                               tol = tol,
                               no.pen = no.pen,
                               control.solver = control.solver,
                               warmupiters = warmupiters,
                               verbose = verbose)
          }))
          coefficients[variable.indices,] <-  Matrix(do.call(cbind, fit[1, ]), sparse = TRUE)
          weights.mat <-  Matrix(do.call(cbind, fit[2, ]), sparse = TRUE)
          # pen.weights.mat[variable.indices,] <-  Matrix(do.call(cbind, fit[3, ]), sparse = TRUE)
          lambdas.mat[variable.indices,] <-  Matrix(do.call(cbind, fit[4, ]), sparse = TRUE)
          z.mat <-  Matrix(do.call(cbind, fit[5, ]), sparse = TRUE)
        } else { # If variable indices == 0
          if(verbose) warning("Relaxed fit wasn't possible due to all coefficients being 0.")
        }
      }
      stopCluster(cl)
    } else { # If parallellize = FALSE
      for(i in 1L:group.maxit){
        # print(i)
        if(i > 1){
          avgcoefs <- rowMeans(coefficients)
          variable.indices = which(avgcoefs > 0) # Only refit nonzero indices
          no.pen.new.indices <- no.pen.start[no.pen.start %in% variable.indices] # Recalculate no.pen indices
          no.pen <- match(no.pen.new.indices, variable.indices)
          start <- matrix(rep(avgcoefs, times = ncol(y)), nrow = length(avgcoefs), ncol = ncol(y))
        } else {
          variable.indices <- 1:ncol(X)
        }
        
        coefficients <- lambdas.mat <- Matrix(0, nrow = ncol(X), ncol = ncol(y), sparse = TRUE)
        weights.mat <- Matrix(0, nrow = nrow(X), ncol = ncol(y), sparse = TRUE)
        
        if(length(variable.indices) == 0) break
        
        
        fit <- do.call(cbind, lapply(1:ncol(y), function(col) {
          L0glm.fit.internal(X = X[,variable.indices,drop=F],
                             y = y[,col,drop=F],
                             family=family,
                             lambda = lambda,
                             gamma = gamma,
                             nonnegative = nonnegative,
                             normalize = normalize,
                             offset = as.vector(offset[col, drop = F]),
                             weights = as.vector(weights[,col,drop=F]),
                             warm.start = warm.start,
                             prior.mean = prior.mean[variable.indices],
                             start = as.vector(start[variable.indices, col, drop = F]),
                             lower = lower[variable.indices],
                             upper = upper[variable.indices],
                             maxit = maxit,
                             thresh = thresh,
                             solver = solver,  
                             method = method,  
                             tol = tol,
                             no.pen = no.pen,
                             control.solver = control.solver,
                             warmupiters = warmupiters,
                             verbose = verbose)
        }))
        coefficients[variable.indices,] <-  Matrix(do.call(cbind, fit[1, ]), sparse = TRUE)
        weights.mat <-  Matrix(do.call(cbind, fit[2, ]), sparse = TRUE)
        # pen.weights.mat[variable.indices,] <-  Matrix(do.call(cbind, fit[3, ]), sparse = TRUE)
        lambdas.mat[variable.indices,] <-  Matrix(do.call(cbind, fit[3, ]), sparse = TRUE)
        z.mat <-  Matrix(do.call(cbind, fit[4, ]), sparse = TRUE)
      }
      
      if(relaxed){
        # Apply relaxed group L0 feature selection
        # using 1/ avg coefficients over channels from previous fit as starting values for another L0 GLM fit but now using lambda=0, 
        # i.e. using a nonnegative Poisson GLM, using variables selected earlier via iterated L0 GLMs
        avgcoefs = rowMeans(coefficients)
        variable.indices = which(avgcoefs!=0)
        no.pen.new.indices <- no.pen.start[no.pen.start %in% variable.indices] # Recalculate no.pen indices
        no.pen <- match(no.pen.new.indices, variable.indices)
        
        if(length(variable.indices) != 0){
          start <- matrix(rep(avgcoefs, times = ncol(y)), nrow = length(avgcoefs), ncol = ncol(y))
          coefficients <- lambdas.mat <- Matrix(0, nrow = ncol(X), ncol = ncol(y), sparse = TRUE)
          weights.mat <- Matrix(0, nrow = nrow(X), ncol = ncol(y), sparse = TRUE)
          
          fit <- do.call(cbind, lapply(1:ncol(y), function(col) {
            L0glm.fit.internal(X = X[,variable.indices,drop=F],
                               y = as.vector(y[,col,drop=F]),
                               family = family,
                               lambda = 1e-30,
                               gamma = gamma,
                               nonnegative = nonnegative,
                               normalize = normalize,
                               weights = as.vector(weights[,col,drop=F]),
                               start = as.vector(start[variable.indices, col, drop = F]),
                               lower = lower[variable.indices],
                               upper = upper[variable.indices],
                               maxit = maxit,
                               warm.start = warm.start,
                               prior.mean = prior.mean[variable.indices],
                               thresh = thresh,
                               solver = solver,
                               method = method,
                               tol = tol,
                               no.pen = no.pen,
                               control.solver = control.solver,
                               warmupiters = warmupiters,
                               verbose = verbose)}))
          
          coefficients[variable.indices,] <-  Matrix(do.call(cbind, fit[1, ]), sparse = TRUE)
          weights.mat <-  Matrix(do.call(cbind, fit[2, ]), sparse = TRUE)
          # pen.weights.mat[variable.indices,] <-  Matrix(do.call(cbind, fit[3, ]), sparse = TRUE)
          lambdas.mat[variable.indices,] <-  Matrix(do.call(cbind, fit[3, ]), sparse = TRUE)
          z.mat <-  Matrix(do.call(cbind, fit[4, ]), sparse = TRUE)
        }
      }
    }
    weights.ret <- weights.mat
    # pen.weights <- pen.weights.mat
    lambdas <- lambdas.mat
    z <- z.mat
  } else { # Single variable
    fit <- L0glm.fit.internal(X = X, 
                              y = as.vector(y),
                              weights = weights,
                              family = family,
                              nonnegative = nonnegative,
                              normalize = normalize,
                              offset = offset,
                              start = start,
                              lower = lower,
                              upper = upper,
                              lambda = lambda, 
                              warm.start = warm.start,
                              prior.mean = prior.mean,
                              gamma = gamma,
                              thresh = thresh,
                              solver = solver, 
                              method = method, 
                              maxit = maxit,
                              tol = tol,
                              no.pen = no.pen,
                              control.solver = control.solver,
                              warmupiters = warmupiters,
                              verbose = verbose)
    
    coefficients <- fit$coefficients
    # pen.weights <- fit$pen.weights
    lambdas <- fit$lambdas
    weights.ret <- fit$weights
    z <- fit$z
    
    if(relaxed){
      # Apply relaxed group L0 feature selection
      # using 1/ avg coefficients over channels from previous fit as starting values for another L0 GLM fit but now using lambda=0, 
      # i.e. using a nonnegative Poisson GLM, using variables selected earlier via iterated L0 GLMs
      variable.indices = which(coefficients!=0)
      no.pen.new.indices <- no.pen.start[no.pen.start %in% variable.indices] # Recalculate no.pen indices
      no.pen <- match(no.pen.new.indices, variable.indices)
      start <- coefficients
      
      fit <- L0glm.fit.internal(X = X[,variable.indices, drop = F],
                                y = y,
                                family = family,
                                weights = weights,
                                nonnegative = nonnegative,
                                normalize = normalize,
                                offset = offset,
                                start = start[variable.indices],
                                lower = lower[variable.indices],
                                upper = upper[variable.indices],
                                lambda = 1e-30,
                                warm.start = warm.start,
                                prior.mean = prior.mean[variable.indices],
                                gamma = gamma,
                                thresh = thresh,
                                solver = solver,
                                method = method,
                                maxit = maxit,
                                tol = tol,
                                no.pen = no.pen,
                                control.solver = control.solver,
                                warmupiters = warmupiters,
                                verbose = verbose)
      
      coefficients <- lambdas <- rep(0, ncol(X))
      weights.ret <- rep(0, nrow(X))
      
      coefficients[variable.indices] <- fit$coefficients
      # pen.weights[variable.indices] <- fit$pen.weights
      lambdas[variable.indices] <- fit$lambdas
      z <- fit$z
      weights.ret <- fit$weights
    }
    
    
    # Threshold optimization
    
    
    # # Option 1: with optimize function. 0.49s for SC p=n=100
    # thresh.post <- optimize(optimize.threshold, interval = c(0, max(coefficients)), coefficients = coefficients, Xmat = X, y = y, IC = IC, family = family, maximum = FALSE)
    # coefficients[abs(coefficients) < thresh.post$minimum] = 0
    
    # # Option 2: with optim package. https://www.rdocumentation.org/packages/stats/versions/3.6.2/topics/optim
    # # method "SANN" => VERY slow (136.78s for n=p=100).
    # # method "Nelder-Mead" => unreliable for 1 dimension.
    # thresh.post <- optim(par = thresh,
    #                      fn = optimize.threshold,
    #                      coefficients = coefficients,
    #                      Xmat = X,
    #                      y = y,
    #                      IC = IC,
    #                      family = family,
    #                      method = "Brent"  # "SANN" or "Brent"
    # )
    # # Gives a negative threshold
    # coefficients[abs(coefficients) < thresh.post$par] = 0
    
    # # Option 3: package DEoptim. https://cran.r-project.org/web/packages/DEoptim/DEoptim.pdf. 27.83s
    # thresh.post <- DEoptim(fn = optimize.threshold, lower = thresh, upper = max(coefficients),
    #                        coefficients = coefficients,
    #                        Xmat = X,
    #                        y = y,
    #                        IC = IC,
    #                        family = family)
    # coefficients[abs(coefficients) < thresh.post$optim$bestmem] = 0
    
    # All three threshold optimizations give a threshold that's too high and only leaves 1 nonzero coefficient except for optim method "SANN", which gives a negative threshold
    
  }
  
  weights.ret[is.infinite(weights)] <- 1e11
  # pen.weights[is.infinite(pen.weights)] <- 1e11
  lambdas[is.infinite(lambdas)] <- 1e11
  
  return(list(coefficients = coefficients, weights = weights.ret, 
              # pen.weights = pen.weights, 
              init.lambda = lambda, 
              lambdas = lambdas, family = family, z = z, X = X, y = y))
}

#' @describeIn L0glm
#'
#'  Fits a generalized linear model with L0 regularization and option for nonnegativity and box constraints. It takes as input parameters the design matrix X, the response 
#'  variable y, regularization parameters, solver options, and control parameters. The result is a fitted model with coefficients estimated using 
#'  the specified regularization method and solver. The function it is called by the higher level \code{L0glm.fit}.
#'
#' @export
L0glm.fit.internal = function(X, 
                              y, 
                              family = poisson(identity),
                              weights = rep(1, ncol(X)),
                              start = NULL,
                              offset = rep(0, nrow(X)),
                              lambda = 1, 
                              no.pen = 0,
                              nonnegative = FALSE,
                              normalize = TRUE,
                              solver = "eigen", 
                              method = 7L, 
                              lower = rep(-.Machine$double.xmax, ncol(X)),
                              upper = rep(.Machine$double.xmax, ncol(X)),
                              maxit = 25,
                              warm.start = 0.9,
                              prior.mean = NULL,
                              warmupiters = 1,
                              gamma = 2,
                              thresh = 1e-5,
                              tol = 1E-10,
                              control.solver = do.call("control.solver.gen", list(solver = solver, method = method)),
                              verbose = FALSE) { # nr of iterations before obs weights are updated in addition to penalty weights in each iteration, 3 or 4 gave best performance

  # NOTE currently I haven't implemented any SCREENING RULES like
  # http://proceedings.mlr.press/v119/atamturk20a/atamturk20a.pdf
  # or sure independent screening prescreening, as implemented in abess
  # https://cran.r-project.org/web/packages/abess/abess.pdf
  # Implemented these might further speedup the algo.
  
  # Normalize columns of X to unit L2 norm? If so, calculate scaling
  if(normalize) { scaling = scaleX(X) } else { # L2 norm of columns of X
                  scaling = rep(1, ncol(X)) }
  
  # if (!is.null(start)) { if (sum(start==0)==length(start)) start = NULL } # interpret all zero start values as start values still requiring initialisation 
  
  if (!is(family, "family")) family = family()
  variance = family$variance # variance function for given family
  linkinv = family$linkinv # inverse link function
  link = family$linkfun # link function
  init = family$initialize # initialisation function
  dev.resids = family$dev.resids # deviance residuals function
  mu.eta = family$mu.eta # function of derivative of the expected values
  
  if (!is.function(variance) || !is.function(linkinv) )
    stop("'family' argument seems not to be a valid family object", call. = FALSE)

  etastart = NULL
  mustart = NULL
  n = NULL
  nobs <- nrow(X)    # needed by the initialize expression below
  p <- nvars <- ncol(X)   # needed by the initialize expression below
  
  eval(init) # initializes n and m (total nr of trials for binomial) and fitted values mustart based on y (mu=expected value on response scale)

  if (is.null(start)) {  
    eta = as.matrix(link(mustart))
    # to initialise using an orthogonal initialisation
    # beta <-  beta_old <- start <- init_coefs(X = X, weights = weights, offset = offset, mu = mu, family = family, lambda = lambda)
    # eta = as.matrix(offset + as.vector(if (p == 1L) X * start else X %*% start)) # eta = expected value on link scale
    # to initialise with constant starting values
    beta <-  beta_old <- start <- start_coefs(X=X, family=family) # initial model coefficients - e.g. sqrt(3) correspond in a Bayesian sense to SD on Gaussian prior of 3, which is most common prior in Bayesian stats (lambda=1/start^2 and lambda=1/SD prior)
  } else {  
    # eta = as.matrix(link(mustart))
    beta <- beta_old <- start # when starting coefficient values were provided
    # IF STARTING VALUES ARE VERY GOOD WE COULD USE
    eta = as.matrix(offset + as.vector(if (p == 1L) X * start else X %*% start)) # eta = expected value on link scale
  }
  names(beta) = colnames(X)
  mu = linkinv(eta) # expected value on response scale
  dev = sum(dev.resids(y, mu, weights)) # deviance 
  dev_old = 0
  if (is.null(start)) { nonzero = as.vector(beta!=0) } else { nonzero = as.vector(start!=0) } # nonzero coefficients
  # mask <- rep(FALSE, p)
  for (i in 1L:maxit) {
    varg = variance(mu) # variance
    
    # good = which(!is.na(weights) & !(weights==0) & !is.infinite(weights) & (gprime != 0)) # valid rows
    # if (i==1|i>warmupiters) {
      if (family$link == "identity"){ # simplified formula and faster than formula in else statement
        W <- W.ret <- as.vector(weights / varg) # 1/variance (* weights) with identity link, where variance = 1 with Gaussian noise, variance = mu with Poisson noise, variance = mu^2 with Gamma noise
        good = which(!is.na(W) & !(W==0) & !is.infinite(W)) # valid rows # (gprime != 0)
        z.ret <- (y - offset) # working (adjusted) response (returned non-subsetted version)
        z <- z.ret[good] # subset used for fit
      } else {
        gprime = mu.eta(eta) # derivative of the expected values
        good = which((weights != 0) & (gprime != 0) & !is.infinite(weights) & !is.na(weights)) # valid rows
        z.ret <- (eta - offset) + (y - mu) / gprime # working (adjusted) response
        z <- z.ret[good] 
        W.ret <- weights * as.vector(gprime^2 / varg) # updated weights 
        W <- W.ret[good]
      }
    
    if(!is.null(prior.mean)){ 
      center = prior.mean # nonzero centered ridge regression
    } else {
      center = NULL # zero centered ridge regression
    }
    
    # update ridge penalties
    pen.weights <- AR.weights(beta = beta, gamma = gamma) # adaptive ridge pentalty weights
    lambdas = lambda*pen.weights # ridge penalties on individual coefficients
    lambdas[no.pen] = 0
    
    if (length(good)==0) {
      conv <- FALSE
      if(verbose) print(gettextf("No observations informative at iteration %d",
                                 i), domain = NA)
      break
    }
    
    beta_old = beta

    # weighted least square step in IRLS algo, here replaced by ridge regression to
    # add automatic regularisation and with possible box constraints
    res <- lmridge(X = X[good, nonzero, drop=F], 
                   y = z,
                   weights = W[good],
                   # pen.weights = pen.weights[good], 
                   lambdas = lambdas[nonzero],
                   nonnegative = nonnegative,
                   scaling = scaling[nonzero],
                   start = start[nonzero], # as.vector(crossprod(Xwaug, ywaug) / colSums(Xwaug^2)),
                   lower = lower[nonzero], 
                   upper = upper[nonzero],
                   prior.mean = center[nonzero],
                   solver = solver,
                   control.solver = control.solver,
                   method = method)
    if(sum(res) != 0){
      beta[nonzero] <- res
    } 

    beta[nonzero][abs(beta[nonzero]) < thresh] = 0
    nonzero = as.vector(beta!=0) # nonzero coefficients
    if(sum(nonzero) == 0){
      conv <- TRUE
      if(verbose) warning("All coefficients penalized to zero")
      break
    }
    if (any(!is.finite(beta))) {
      conv <- FALSE
      if(verbose) warning(gettextf("Non-finite coefficients at iteration %d", i), domain = NA)
      break
    }
    
    ## calculate updated values of eta and mu with the new coefs:
    eta = as.matrix(X[,nonzero,drop=F] %*% beta[nonzero] + offset) # expected value / predictions on link scale
    mu = linkinv(eta) # expected value / predictions on response scale
    dev_old = dev
    dev = sum(dev.resids(y, mu, weights)) # deviance
    
    
    # reldiff <- 2*abs((beta-beta_old)/(beta+beta_old))
    # mask <- reldiff <= tol # keep coefficients fixed in subsequent iterations if they converged
    # mask[is.na(mask)] <- TRUE
    # stop.loop <- sum(mask) >= (p-1)
    # if(stop.loop) break # & i > warmupiters) break 
    
    # if (abs(dev - dev_old) / (0.1 + abs(dev)) < tol) break # This gives error because dev goes to infinity
    # if (norm(beta-beta_old, "2") < tol) break
    rel_change = sqrt(sum((beta - beta_old)^2)) / sqrt(sum(beta^2)) # relative change in coefficient vector (Euclidean distance, ie L2 norm, between old & new coefficients over L2 norm of current coefficients)
    if (rel_change < tol) break
    dev_old = dev
    beta_old = beta 
  }

  return(list(coefficients = as.vector(beta), weights = as.vector(W.ret), 
              # pen.weights = as.vector(pen.weights), 
              lambdas = as.vector(lambdas), z = as.vector(z.ret)))
}

#' @describeIn L0glm
#'
#' Helper function used in the \code{L0glm.fit} function for parallel computation. It takes a subset of column indices cols along with 
#' other parameters such as regularization parameters, solver options, and data matrices X and y. It performs L0 regularization using 
#' the \code{L0glm.fit.internal} function on each column independently and returns the results as a matrix. The function supports weighting 
#' of observations and nonnegative constraints if specified. 
#'
#'
#' @export
fun <- function(cols, lambda, gamma, thresh, solver, method, warmupiters, nonnegative, normalize, X, y, family, warm.start = 0.9, 
                prior.mean = NULL, weights = NULL, start = NULL, lower, upper, verbose = FALSE, maxit, tol, offset, no.pen = 0, 
                control.solver = do.call("control.solver.gen", list(solver = solver, method = method))) { 
  # require(L0glm)
  # devtools::load_all(".")
  fit <- lapply(cols, function(col) {
    y = as.vector(y[,col,drop=F])
    
    # Call L0glm.fit.internal
    L0glm.fit.internal(X = X,
                       y = y,
                       family = family,
                       lambda = lambda,
                       gamma = gamma,
                       weights = as.vector(weights[,col,drop=F]),
                       start = as.vector(start[, col, drop = F]),
                       maxit = maxit,
                       tol = tol,
                       no.pen = no.pen,
                       lower = lower,
                       offset = as.vector(offset[,col, drop = F]),
                       upper = upper,
                       prior.mean = prior.mean,
                       thresh = thresh,
                       solver = solver,
                       nonnegative = nonnegative,
                       normalize = normalize,
                       method = method,
                       warmupiters = warmupiters,
                       verbose = verbose)
  })
  
  return(fit)
}