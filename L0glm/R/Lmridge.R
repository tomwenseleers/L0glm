#' Fit Constrained Ridge Regularised Weighted Least Squares Regression using
#' chosen Solver
#'
#' @name lmridge
#' @aliases lmridge
#' @title Fits a ridge regularised weighted least squares regression using a
#'   chosen solver subject to optional nonnegativity or box constraints on the
#'   coefficients.
#'
#' @param X A numeric matrix or sparse matrix of predictors (design matrix).
#' @param y A numeric vector of responses.
#' @param lambdas Numeric value or vector specifying the ridge penalty
#'   parameter(s).
#' @param weights Optional numeric vector of observation weights. Default is
#'   \code{NULL}.
#' @param lower Numeric vector specifying lower bounds on the coefficients.
#'   Default is a vector of \code{-Inf}.
#' @param upper Numeric vector specifying upper bounds on the coefficients.
#'   Default is a vector of \code{Inf}.
#' @param nonnegative Logical; if \code{TRUE}, nonnegativity constraints are
#'   imposed on the coefficients (equivalent to setting \code{lower = 0}).
#'   Default is \code{FALSE}.
#' @param scaling Numeric vector specifying scaling factors for the columns of
#'   \code{X}. Default is a vector of ones (no scaling). This allows scaling of
#'   columns of \code{X}, e.g., by their L2 norm.
#' @param prior.mean Numeric vector specifying prior means for Gaussian priors
#'   implied by the ridge penalties. Default is a vector of zeros (i.e. zero
#'   centered means) to shrink to zero. Nonzero values will result in a targeted
#'   nonzero-centered ridge regression being used instead.
#' @param solver Character string specifying which solver to use. Options are
#'   \code{"eigen"}, \code{"glmnet"}, \code{"osqp"}, \code{"nnls"}. Default is
#'   \code{"eigen"}.
#' @param method Integer code specifying the method to be used within the
#'   solver. Default is \code{3L} if \code{ncol(X) >= 20000}, otherwise
#'   \code{7L}.
#' @param start Numeric vector of starting values for the coefficients. Default
#'   is a vector of zeros.
#' @param iteration Integer specifying the iteration number, used internally for
#'   iterative algorithms. Default is \code{1}.
#' @param control.solver List of control parameters for the solver. Default is
#'   generated by \code{control.solver.gen(solver = solver, method = method)}.
#' @param verbose Logical; if \code{TRUE}, additional information is printed
#'   during computation. Default is \code{FALSE}.
#'
#' @return A numeric vector of estimated coefficients.
#'
#' @details The \code{lmridge} function fits a ridge regression model of the
#' form: \deqn{\beta = \arg \min_{\beta} \left\{ \frac{1}{2} \| y - X \beta
#' \|_2^2 + \lambda \| \beta - \mu \|_2^2 \right\}} where \eqn{\lambda} is the
#'   ridge penalty parameter and \eqn{\mu} is the prior mean of the coefficients
#'   (specified by \code{prior.mean}).
#'
#'   The function supports optional bounds on the coefficients via the
#'   \code{lower} and \code{upper} parameters and can impose nonnegativity
#'   constraints if \code{nonnegative = TRUE}.
#'
#'   The \code{scaling} parameter allows scaling of the predictors. If scaling
#'   is applied, the coefficients are rescaled back to the original scale before
#'   being returned.
#'
#'   Different solvers can be specified via the \code{solver} parameter:
#' \describe{
#'   \item{\code{"eigen"}}{Uses the \code{Eigen} package to solve the ridge
#'   regression problem using one of several solvers (see \code{method} option).}
#'   \item{\code{"glmnet"}}{Uses the \code{bigGlm} function in the \code{\link[glmnet]{glmnet}} package to solve the ridge regression problem.}
#'   \item{\code{"osqp"}}{Uses the \code{\link[osqp]{osqp}} package (Operator Splitting Quadratic Program solver) to solve the problem with constraints. Most appropriate when box or nonnegativity constraints are applied.}
#'   \item{\code{"nnls"}}{Uses non-negative least squares algorithm. Only applicable when \code{nonnegative = TRUE} and no other bounds are specified.}
#' }
#'
#'   The \code{method} parameter specifies the specific method to be used when
#'   the \code{"eigen"} solver is used (1=Householder QR, 2=Householder QR with
#'   column pivoting, 3=LSCG with identity preconditioner, 4=LSCG with diagonal
#'   preconditioner, 5=CG with identity preconditioner, 6=CG with diagonal
#'   preconditioner, 7=Cholesky LLT, 8=Cholesky LDLT).
#'
#' @seealso \code{\link[glmnet]{glmnet}}, \code{\link[osqp]{osqp}},
#' \code{\link[nnls]{nnls}}, \code{\link{control.solver.gen}}
#'
#' @examples
#' \dontrun{
#' # Simulate some data
#' set.seed(123)
#' n <- 100
#' p <- 10
#' X <- matrix(rnorm(n * p), n, p)
#' beta_true <- rnorm(p)
#' y <- X %*% beta_true + rnorm(n)
#'
#' # Fit ridge regression model with default settings
#' beta_est <- lmridge(X, y, lambdas = 1)
#'
#' # Fit ridge regression with nonnegativity constraints using the osqp solver
#' beta_est_nn <- lmridge(X, y, lambdas = 1, nonnegative = TRUE, solver = "osqp")
#'
#' # Compare estimated coefficients to true coefficients
#' plot(beta_true, beta_est, xlab = "True Coefficients", ylab = "Estimated Coefficients",
#'      main = "Ridge Regression Coefficients")
#' abline(0, 1, col = "red")
#' }
#'
#' @export
#' @author Tom Wenseleers \email{tom.wenseleers@kuleuven.be} \\ Laboratory of
#' Socioecology and Social Evolution, KU Leuven \\
#' \url{https://bio.kuleuven.be/eeb/tw/research} \\ ORCID:
#' \href{https://orcid.org/0000-0002-1434-861X}{0000-0002-1434-861X}
lmridge <- function(X, y, 
                    lambdas = rep(0, ncol(X)),
                    weights = NULL,
                    nonnegative = FALSE,
                    lower = if (nonnegative) { rep(0,ncol(X)) } else { rep(-.Machine$double.xmax,ncol(X)) },
                    upper = rep(.Machine$double.xmax,ncol(X)),
                    scaling = rep(1, ncol(X)), # to allow scaling of columns of X, eg by L2 norm
                    prior.mean = NULL,
                    solver = "eigen",
                    method = ifelse(ncol(X)>=20000, 3L, 7L),
                    start = rep(0, ncol(X)),
                    iteration = 1, # IRLS iteration - passing this as extra info
                    control.solver = do.call("control.solver.gen", list(solver = solver, method = method)),
                    verbose = FALSE){
  
  # scale columns of X if desired
  if (sum(scaling)!=length(scaling)) { 
    X <- Matrix(X %*% Matrix::Diagonal(x = 1 / scaling), sparse=issparse(X)) 
    start <- start * scaling }
  
  # If nonnegative is true and no lower bound is provided, or the lower bound is larger than 0, it is clipped to 0
  if(nonnegative) lower[lower < 0] <- 0
  Xw <- Xweights(X, weights)
  yw <- Yweights(y, weights)
  # if (!issparse(Xw)) { Xw = as.matrix(Xw) }
  yw[is.nan(yw)] <- 0
  
  if(is.null(prior.mean)){
    prior.mean = rep(0, ncol(X))
  } else if (length(as.vector(prior.mean)) == 1){
    prior.mean = rep(prior.mean, ncol(X))
  } else if (length(as.vector(prior.mean)) != ncol(X)) {
    stop("Prior.mean needs to be a vector of length p or a numerical.")
  }
  
  if (solver == "osqp") {
    coefs <- lmridge.osqp(Xw = Xw, yw = yw, lambdas = lambdas, start = start, 
                          prior.mean = prior.mean, 
                          lower = lower, upper = upper, 
                          control.solver = control.solver,
                          iteration = iteration)
    
  } else if (solver == "glmnet") {
    coefs <- lmridge.glmnet(Xw = Xw, yw = yw, lambdas = lambdas, 
                            lower = lower, upper = upper, 
                            control.solver = control.solver,
                            prior.mean = prior.mean,
                            iteration = iteration)
    
    } else if (solver == "eigen") {
    coefs <- lmridge.eigen(Xw = Xw, yw = yw, 
                             lambdas = lambdas, 
                           start = start, prior.mean = prior.mean,
                           lower = lower, upper = upper, 
                           control.solver = control.solver,
                           verbose = verbose,
                           iteration = iteration)
    
  } else if (solver == "nnls") {
    coefs <- lmridge.nnls(Xw = Xw, yw = yw, lambdas = lambdas, prior.mean = prior.mean,
                          lower = lower, upper = upper, control.solver = control.solver,
                          iteration = iteration)
  } else {
    stop("Invalid solver choice") }
  
  # rescale coefficients to original scale
  if (sum(scaling)!=length(scaling)) { coefs = coefs / scaling }
  
  if (sum(is.na(coefs))==length(coefs)) { warning("Ridge solver failed, returning starting coefficients.")
                                          return(start) } 
  
  return(coefs)
}



lmridge.osqp <- function(Xw, 
                         yw, 
                         lambdas = rep(0, ncol(Xw)), 
                         lower, upper, start, 
                         control.solver = do.call("control.solver.gen", list(solver = "eigen", method = 7L)), 
                         prior.mean = NULL,
                         iteration = 1){
  if (!inherits(Xw, "dgCMatrix")) {
    Xw = as(Matrix(Xw, sparse = TRUE), "generalMatrix") # here always coercing Xw to sparse format
    # Xw <- Matrix(Xw, sparse = TRUE)
  } 
  
  if((sum(lambdas)!=0)) {
    Xwaug <- row_augX(Xw, lambdas)
    ywaug <- augY(yw, ncol(Xwaug), lambdas = lambdas, prior.mean = prior.mean) 
  } else {
    Xwaug <- Xw
    ywaug <- yw
  }
  
  if(control.solver$rowaug == TRUE){
    XtX <- crossprod(Xwaug)
    Xty <- crossprod(Xwaug, ywaug)
  } else {
    if (issparse(Xw)){
      XtX <- as(Matrix(crossprod(Xwaug), sparse=T), "generalMatrix")
    } else {
      XtX <- crossprod(Xwaug)
    }
    Xty <- as.matrix(crossprod(Xwaug, 
                               augY(yw, ncol(Xw), 
                                    lambdas = lambdas, 
                                    prior.mean = prior.mean)))
  }
  
  # Obtain settings  and create model
  settings <- do.call(osqp::osqpSettings, control.solver[-7])
  if (sum(start)!=0) settings <- c(settings, warm_start = TRUE) else 
    settings <- c(settings, warm_start = FALSE)
  
  model <- osqp::osqp(P = XtX, q = -Xty, 
                A = .sparseDiagonal(ncol(Xw)), # Diagonal(n = ncol(Xw)),
                l = lower, u = upper, pars = settings)
  if(is.null(start)) start <- rep(0, ncol(Xw))
  model$WarmStart(x=start)
  
  # solve model
  coefs <- model$Solve()$x
  coefs <- clamp(coefs, lower, upper) # fitted coefficients sometimes go very slightly outside constraint zone due to numerical inaccuracies in solver - this is fixed here via clipping
  return(coefs)
}


lmridge.glmnet <- function(Xw, yw, 
                           lambdas = rep(0, ncol(Xw)), 
                           lower, upper, 
                           control.solver = do.call("control.solver.gen", list(solver = "glmnet")), 
                           prior.mean = NULL,
                           iteration = 1){
  if (iteration<=5&(ncol(Xw)>1000|nrow(Xw)>1E6)) {
    # for first 5 IRLS iterations & for larger problems (p>1000 or n>1E6) use glmnet to solve ridge regression
    n <- nrow(Xw)
    sd_y <- sqrt(var(yw)*(n-1)/n)
    lambda <- mean(lambdas)
    penalty.factor <- lambdas/lambda
    penalty.factor[is.na(penalty.factor)] <- 1
    standardize <- control.solver$standardize
    thresh <- control.solver$thresh
    maxit <- control.solver$maxit
    lower.limits <- c(-Inf, lower)
    upper.limits <- c(Inf, upper)
    model <- do.call(glmnet,
                     args=list(x=Xw, y=yw, alpha=0, 
                               standardize = standardize, 
                               standardize.response = TRUE, 
                               lambda = sd_y*lambda/n, 
                               penalty.factor=penalty.factor,
                               lower.limits = lower.limits, 
                               upper.limits = upper.limits,
                               family = "gaussian", 
                               nlambda = 1,
                               intercept = F, 
                               thresh = thresh,
                               maxit = maxit))
    coefs <- as.vector(coef(model, s = sd_y*lambda/n, # exact = TRUE, 
                            x = Xw, y = yw, 
                            lower.limits = lower.limits, 
                            upper.limits = upper.limits,
                            penalty.factor = penalty.factor))[-1]
  } else {
  
  # for later IRLS iterations use more accurate bigGlm to solve ridge regression
    
  # Set path depending on dimensions of Xw
   if(sum(lambdas) == 0 | ncol(Xw) > nrow(Xw)){ # avoid numerical instabilities if lambdas is 0 and p>=n
     path = TRUE
   } else {
     path = FALSE
   }

   # Obtain Xwaug and ywaug
   if((sum(lambdas)!=0)) {
     Xwaug <- row_augX(Xw, lambdas)
     ywaug <- augY(yw, ncol(Xwaug),
                   lambdas = lambdas,
                   prior.mean = prior.mean)
   } else {
     Xwaug <- Xw
     ywaug <- yw
   }
   model <- glmnet::bigGlm(x = Xwaug,
                   y = ywaug,
                   intercept = FALSE,
                   standardize = control.solver$standardize,
                   standardize.response = TRUE,
                   lower.limits = c(-Inf, lower),
                   upper.limits = c(Inf, upper),
                   family = "gaussian",
                   path = path,
                   thresh = control.solver$thresh,
                   maxit = control.solver$maxit)
   coefs <- coef(model)[-1]
  }

  # apply box constraints in case coefs would slightly fall outside bounds
  coefs <- clamp(coefs, lower, upper) 
  return(coefs)
}


lmridge.nnls <- function(Xw, yw, lambdas = rep(0, ncol(Xw)), lower, upper, 
                         control.solver, 
                         prior.mean = NULL,
                         iteration = 1){
  # Obtain Xwaug and ywaug
  if(!is.null(lambdas)&(sum(lambdas)!=0)) {
    Xwaug <- row_augX(Xw, lambdas)
    ywaug <- augY(yw, ncol(Xwaug), lambdas = lambdas, prior.mean = prior.mean)
  } else {
    Xwaug <- Xw
    ywaug <- yw
  }
  
  coefs <- nnls::nnls(A=as.matrix(Xwaug), b=ywaug)$x
  return(coefs)
}


lmridge.eigen <- function(Xw, yw, 
                          lambdas = rep(0, ncol(Xw)), 
                          lower = rep(-.Machine$double.xmax,ncol(Xw)), 
                          upper = rep(.Machine$double.xmax,ncol(Xw)), 
                          start = rep(0, ncol(Xw)), 
                          control.solver = do.call("control.solver.gen", 
                                                   list(solver = "eigen", method = 7L)), 
                          prior.mean = rep(0, ncol(Xw)),
                          verbose = FALSE,
                          iteration = 1){ 
  rowaug <- control.solver$rowaug && any(lambdas != 0) # ----- 1. make 'row augmentation if, and only if, some lambdas > 0'
  
  lambda = mean(lambdas)
  pen.weights = lambdas / lambda 
  pen.weights[is.na(pen.weights)] = 1
  if (issparse(Xw)) { Xw = as(Matrix(Xw, sparse=T), "generalMatrix") } else { 
    Xw = as.matrix(Xw) } 
  
  if ((ncol(Xw) > nrow(Xw)*100)&control.solver$rowaug) { # &(control.solver$method != "LSCG")
    control.solver$rowaug <- FALSE
    if(verbose&control.solver$method != "LSCG") print("Row augmentation is not recommended for p > n with this solver. Using Woodbury identity optimized normal equations appropriate for p > n case instead.")
  }
  
  if (control.solver$method == "QR") {
    if (control.solver$rowaug) {
      # Obtain Xwaug and ywaug
      if (rowaug) {
        Xwaug <- row_augX(Xw, lambdas) # at least one lambda nonzero
        ywaug <- augY(yw, ncol(Xwaug), lambdas = lambdas, prior.mean = prior.mean)
      } else {
        Xwaug <- Xw
        ywaug <- yw
      }
      
      if (issparse(Xwaug)){
        coefs <- solve_sparse_QR(A = Xwaug,
                                 b = ywaug)$coefficients
      } else {
        coefs <- solve_dense_QR(A = Xwaug,
                                b = ywaug, 
                                pivot = control.solver$pivot)$coefficients
      }
    } else {
      
      D <- Diagonal(x=1/pen.weights)
      if(nrow(Xw)*100 >= ncol(Xw)){
        if(issparse(Xw)){
          coefs <- as.vector(solve_sparse_QR(A = as(D %*% Matrix::crossprod(Xw) + Diagonal(x=rep(lambda, ncol(Xw))), "generalMatrix"),
                                             b = as.matrix(D %*% Matrix::crossprod(Xw,yw) + lambda*Matrix::crossprod(D, prior.mean)))$coefficients)
        } else { # if it's dense
          coefs <- as.vector(solve_dense_QR(A = as.matrix(D %*% Matrix::crossprod(Xw) + Diagonal(x=rep(lambda, ncol(Xw)))),
                                            b = as.matrix(D %*% Matrix::crossprod(Xw,yw) + lambda*Matrix::crossprod(D, prior.mean)),
                                            pivot = control.solver$pivot)$coefficients)
        }
      } else { # if p >> n
        if(issparse(Xw)){
          # Precompute some values
          DXw <- Matrix::tcrossprod(D, Xw)
          y_star <- as.vector(yw - Xw %*% prior.mean)
          
          # Calculate beta using Woodbury identity
          coefs <- as.vector(prior.mean + DXw %*% solve_sparse_QR(A = as(Xw %*% DXw + Diagonal(x=rep(lambda, nrow(Xw))), "generalMatrix"),
                                                                  b = y_star)$coefficients) 
        } else { # if it's dense
          # Precompute some values
          DXw <- Matrix::tcrossprod(D, Xw)
          y_star <- as.vector(yw - Xw %*% prior.mean)
          
          # Calculate beta using Woodbury identity
          coefs <- as.vector(prior.mean + DXw %*% solve_dense_QR(A = as.matrix(Xw %*% DXw + Diagonal(x=rep(lambda, nrow(Xw)))),
                                                                 b = y_star,
                                                                 pivot = control.solver$pivot)$coefficients)
        }
      }
    }
  } else if (control.solver$method == "LSCG") {
    if (control.solver$rowaug) {
      # Obtain Xwaug and ywaug
      if(!is.null(lambdas)) {
        Xwaug <- row_augX(Xw, lambdas)
        ywaug <- augY(yw, ncol(Xwaug), lambdas = lambdas, prior.mean = prior.mean)
      } else {
        Xwaug <- Xw
        ywaug <- yw
      }
      
      if(is.null(start)) start <- rep(0, ncol(Xw))
      # start = crossprod(Xwaug, ywaug) / colSums(Xwaug ^ 2) # orthogonal initialisation
      
      # X.n <- sqrt(colSums(Xw^2)) 
      if(issparse(Xwaug)){
        coefs <- solve_sparse_LSCG(A = Xwaug,
                                   b = as.matrix(ywaug),
                                   x0 = as.matrix(start),
                                   tol = control.solver$tol,
                                   maxit = control.solver$maxit,
                                   precond = control.solver$precond)$coefficients 
      } else {
        coefs <- solve_dense_LSCG(A = Xwaug,
                                  b = as.matrix(ywaug),
                                  x0 = as.matrix(start),
                                  tol = control.solver$tol,
                                  maxit = control.solver$maxit,
                                  precond = control.solver$precond)$coefficients
      }
    } else { # Use normal equations
      D <- Diagonal(x=1/pen.weights)

      # Obtain Xwaug and ywaug
      if (sum(lambdas)!=0) {
        Xwaug <- row_augX(Xw, lambdas)
        ywaug <- augY(yw, ncol(Xwaug), lambdas = lambdas, prior.mean = prior.mean)
      } else {
        Xwaug <- Xw
        ywaug <- yw
      }
      
      # start = crossprod(Xwaug, ywaug) / colSums(Xwaug ^ 2) # orthogonal initialisation
      
      if(nrow(Xw)*100 >= ncol(Xw)){
        if(issparse(Xw)){
          coefs <- as.vector(solve_sparse_LSCG(A = as(D %*% Matrix::crossprod(Xw) + Diagonal(x=rep(lambda, ncol(Xw))), "generalMatrix"),
                                               b = as.matrix(D %*% Matrix::crossprod(Xw,yw) + lambda*Matrix::crossprod(D, prior.mean)),
                                               x0 = as.matrix(start),
                                               tol = control.solver$tol,
                                               precond = control.solver$precond)$coefficients)
        } else { # if it's dense
          coefs <- as.vector(solve_dense_LSCG(A = as.matrix(D %*% Matrix::crossprod(Xw) + Diagonal(x=rep(lambda, ncol(Xw)))),
                                              b = as.matrix(D %*% Matrix::crossprod(Xw,yw) + lambda*Matrix::crossprod(D, prior.mean)),
                                              x0 = as.matrix(start),
                                              tol = control.solver$tol,
                                              maxit = control.solver$maxit,
                                              precond = control.solver$precond)$coefficients)
        }
      } else { # if p > n
        DXw <- Matrix::tcrossprod(D, Xw)
        if(issparse(Xw)){
          # Precompute some values
          y_star <- as.vector(yw - Xw %*% prior.mean)

          # Calculate beta using Woodbury identity
          coefs <- as.vector(prior.mean + DXw %*% Matrix::solve(Xw %*% DXw + Diagonal(x=rep(lambda, nrow(Xw))),
                                                                y_star,
                                                                tol = control.solver$tol))
          # TODO: replace Matrix::solve with solve_sparse_LSCG
        } else { # if it's dense
          # Precompute some values
          y_star <- as.vector(yw - Xw %*% prior.mean)
          
          # Calculate beta using Woodbury identity
          coefs <- as.vector(prior.mean + DXw %*% Matrix::solve(Xw %*% DXw + Diagonal(x=rep(lambda, nrow(Xw))),
                                                                y_star,
                                                                tol = control.solver$tol))
          # TODO: replace Matrix::solve with solve_dense_LSCG
        }
      }
    }
  } else if (control.solver$method == "CG") {
    if (control.solver$rowaug) {
      # Obtain Xwaug and ywaug
      if((sum(lambdas)!=0)) {
        Xwaug <- row_augX(Xw, lambdas)
        ywaug <- augY(yw, ncol(Xwaug), lambdas = lambdas, prior.mean = prior.mean)
      } else {
        Xwaug <- Xw
        ywaug <- yw
      }
      
      if(is.null(start)) start <- rep(0, ncol(Xw))
      # start = crossprod(Xwaug, ywaug) / colSums(Xwaug ^ 2) # orthogonal initialisation
      
      if(issparse(Xwaug)){
        coefs <- solve_sparse_CG(A = as(crossprod(Xwaug), "generalMatrix"), 
                                 b = as.matrix(crossprod(Xwaug, ywaug)),
                                 x0 = as.matrix(start),
                                 tol = control.solver$tol,
                                 maxit = control.solver$maxit,
                                 precond = control.solver$precond)$coefficients
        
      } else {
        coefs <- solve_dense_CG(A = crossprod(Xwaug),
                                b = as.matrix(crossprod(Xwaug, ywaug)),
                                x0 = as.matrix(start),
                                tol = control.solver$tol,
                                maxit = control.solver$maxit,
                                precond = control.solver$precond)$coefficients
      }
      
    } else { # normal equations
      D <- Diagonal(x=1/pen.weights)
      
      # Obtain Xwaug and ywaug
      if (sum(lambdas)!=0) {
        Xwaug <- row_augX(Xw, lambdas)
        ywaug <- augY(yw, ncol(Xwaug), lambdas = lambdas, prior.mean = prior.mean)
      } else {
        Xwaug <- Xw
        ywaug <- yw
      }
      
      # start = crossprod(Xwaug, ywaug) / colSums(Xwaug ^ 2) # orthogonal initialisation
      
      if(nrow(Xw)*100 >= ncol(Xw)){
        if(issparse(Xw)){
          coefs <- as.vector(solve_sparse_CG(A = as(D %*% Matrix::crossprod(Xw) + Diagonal(x=rep(lambda, ncol(Xw))), "generalMatrix"),
                                             b = as.matrix(D %*% Matrix::crossprod(Xw,yw) + lambda*Matrix::crossprod(D, prior.mean)),
                                             x0 = as.matrix(start),
                                             tol = control.solver$tol,
                                             maxit = control.solver$maxit,
                                             precond = control.solver$precond)$coefficients)
        } else { # if it's dense
          coefs <- as.vector(solve_dense_CG(A = as.matrix(D %*% Matrix::crossprod(Xw) + Diagonal(x=rep(lambda, ncol(Xw)))),
                                            b = as.matrix(D %*% Matrix::crossprod(Xw,yw) + lambda*Matrix::crossprod(D, prior.mean)),
                                            x0 = as.matrix(start),
                                            tol = control.solver$tol,
                                            maxit = control.solver$maxit,
                                            precond = control.solver$precond)$coefficients)
        }
      } else { # if p > n
        if(issparse(Xw)){
          # Precompute some values
          DXw <- Matrix::tcrossprod(D, Xw)
          y_star <- as.vector(yw - Xw %*% prior.mean)
          
          # Calculate beta using Woodbury identity
          coefs <- as.vector(prior.mean + DXw %*% Matrix::solve(Xw %*% DXw + Diagonal(x=rep(lambda, nrow(Xw))),
                                                                y_star,
                                                                tol = control.solver$tol))
          # TODO replace Matrix::solve with solve_sparse_CG
        } else { # if it's dense
          # Precompute some values
          DXw <- Matrix::tcrossprod(D, Xw)
          y_star <- as.vector(yw - Xw %*% prior.mean)
          
          # Calculate beta using Woodbury identity
          coefs <- as.vector(prior.mean + DXw %*% Matrix::solve(Xw %*% DXw + Diagonal(x=rep(lambda, nrow(Xw))),
                                                                y_star,
                                                                tol = control.solver$tol))
          coefs_solve_largep_dense <- as.vector(prior.mean + DXw %*% Matrix::solve(
            as.matrix(Xw %*% DXw + Diagonal(x=rep(lambda, nrow(Xw)))),
            y_star,
            tol=2*.Machine$double.eps))
          # TODO replace Matrix::solve with solve_dense_CG
        }
      }
    }
  } else if (control.solver$method == "chol") {
    if (control.solver$rowaug) {
      # solve via row augmentation
      # Obtain Xwaug and ywaug
      if (sum(lambdas)!=0) {
        Xwaug <- row_augX(Xw, lambdas)
        ywaug <- augY(yw, ncol(Xwaug), lambdas = lambdas, prior.mean = prior.mean)
      } else {
        Xwaug <- Xw
        ywaug <- yw
      }
      
      if (issparse(Xwaug)) {
        coefs <- solve_sparse_chol(A = as(crossprod(Xwaug),"generalMatrix"), 
                                   b = as.matrix(crossprod(Xwaug, ywaug)), 
                                   pivot = control.solver$pivot,
                                   ordering = control.solver$ordering)$coefficients
      } else {
        coefs <- solve_dense_chol(A = as.matrix(crossprod(Xwaug)),
                                  b = as.matrix(crossprod(Xwaug, ywaug)),
                                  pivot = control.solver$pivot)$coefficients
      }
    } else { 
      # solve from normal equations
      D <- Diagonal(x=1/pen.weights)
      
      if (nrow(Xw)*100 >= ncol(Xw)) {
        # n>=p case
        if (issparse(Xw)) {
          # if it's sparse
          coefs <- as.vector(solve_sparse_chol(A = as(D %*% Matrix::crossprod(Xw) + Diagonal(x=rep(lambda, ncol(Xw))), "generalMatrix"),
                                               b = as.matrix(D %*% Matrix::crossprod(Xw,yw) + lambda*Matrix::crossprod(D, prior.mean)),
                                               pivot = control.solver$pivot,
                                               ordering = control.solver$ordering)$coefficients)
        } else { 
          # if it's dense
          coefs <- as.vector(solve_dense_chol(A = as.matrix(D %*% Matrix::crossprod(Xw) + Diagonal(x=rep(lambda, ncol(Xw)))),
                                              b = as.matrix(D %*% Matrix::crossprod(Xw,yw) + lambda*Matrix::crossprod(D, prior.mean)),
                                              pivot = control.solver$pivot)$coefficients)
        }
      } else { 
        # optimised form for p>n case based on Woodbury identity
        if (issparse(Xw)) {
          # for sparse case
          # Precompute some values
          DXw <- Matrix::tcrossprod(D, Xw)
          y_star <- as.vector(yw - Xw %*% prior.mean)
          # Calculate beta using Woodbury identity
          coefs <- as.vector(prior.mean + DXw %*% solve_sparse_chol(A = as(Xw %*% DXw + Diagonal(x=rep(lambda, nrow(Xw))), "generalMatrix"),
                                                                    b = y_star,
                                                                    pivot = control.solver$pivot,
                                                                    ordering = control.solver$ordering)$coefficients) 
        } else { 
          # for dense case
          # Precompute some values
          DXw <- Matrix::tcrossprod(D, Xw)
          y_star <- as.vector(yw - Xw %*% prior.mean)
          
          # Calculate beta using Woodbury identity
          coefs <- as.vector(prior.mean + DXw %*% solve_dense_chol(A = as.matrix(Xw %*% DXw + Diagonal(x=rep(lambda, nrow(Xw)))),
                                                                   b = y_star,
                                                                   pivot = control.solver$pivot)$coefficients)
        }
      }
    }
  } else {
    stop("Invalid method.")
  }
  
  # some error catching
  if (is.null(coefs)&control.solver$method!="chol") {
    warning(paste0("eigen ", control.solver$method, " solver failed in IRLS iteration ", iteration,", trying Cholesky LLT solver as fallback."))
    coefs <- lmridge.eigen(Xw = Xw, yw = yw,
              lambdas = lambdas,
              lower = lower,
              upper = upper,
              start = start,
              control.solver = do.call("control.solver.gen",
                                       list(solver = "eigen", method = 7L)),
              prior.mean = prior.mean,
              verbose = verbose)
  }
  
  # apply box constraints via clipping
  coefs <- clamp(coefs, lower, upper) # clip coefficients within allowed range - TODO: check if reflect_lower=F might work better to deal with nonnegativity constraints
  
  # returning start values if solver fails
  ifelse(!is.null(coefs), return(coefs), return(start)) 
}


Xweights <- function (X, weights)
{
  ## ---- fast exit : no weighting required --------------------------------
  if (is.null(weights))                return(X)
  
  ## coerce *once* to a plain numeric vector
  if (is.matrix(weights) || inherits(weights, "Matrix"))
    weights <- as.numeric(weights[, 1L])
  
  ## all weights equal to one   - avoid all.equal() for sparse objects -----
  if (length(weights) == 1L) {
    if (weights == 1)               return(X)
  } else {
    ## every entry really equal to 1 ?
    if (all(weights == 1))          return(X)
  }
  
  ## ---- real weighting ----------------------------------------------------
  w_sqrt <- sqrt(weights)
  
  if (issparse(X) || inherits(X, "Matrix")) {
    ## left-multiply by diagonal - keeps sparsity
    return( Matrix::Diagonal(x = w_sqrt) %*% X )
  }
  
  ## dense fallback
  sweep(X, 1L, w_sqrt, `*`)
}


Yweights <- function(y, weights){
  if (!is.null(weights)) {
    return(y * sqrt(weights))
  } else {
    return(y)
  }
}




# UTILITY FUNCTIONS ####

should_augment <- function(lambdas) {
  !is.null(lambdas) && any(lambdas != 0)      # TRUE <=> at least one real penalty
}

# Row augmentation of the covariate matrix if lambda!=0 to add ridge penalty
# Ref :
# https://stats.stackexchange.com/a/164546/27340
# https://stats.stackexchange.com/a/203699/27340
row_augX <- function(Xw, lambdas = NULL){
  if (length(lambdas)==0) lambdas = NULL
  if (should_augment(lambdas)) {
    if (issparse(Xw)) { return( as(Matrix(rbind(Xw, Diagonal(x=sqrt(lambdas))), sparse=T), "generalMatrix") ) } else {
                        return( rbind2(as(Matrix(Xw, sparse=T), "generalMatrix"), Diagonal(x = sqrt(lambdas))) # always returning augmented matrix as sparse dgCMatrix if row augmentation method is requested
                        # return( rbind(Xw, diag(x=sqrt(lambdas)))
                        )
                        }
    } else
    { return(Xw) }

}

# augment y
augY <- function(yw, p, prior.mean = NULL, lambdas = NULL){
  if (length(lambdas)==0) lambdas=NULL
  if (should_augment(lambdas)) {
    if(is.null(prior.mean) | is.null(lambdas) | sum(prior.mean)==0){
      return(c(yw, rep(0, p))) # zero centered row augmentation
    } else {
      return(c(yw, as.numeric(prior.mean) * sqrt(lambdas)))  # nonzero centered row augmentation
    } } else { return(yw) }
}


