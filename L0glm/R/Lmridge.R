#' Fit Constrained Ridge Regularised Weighted Least Squares Regression using
#' chosen Solver
#'
#' @name lmridge
#' @aliases lmridge
#' @title Fits a ridge regularised weighted least squares regression using a
#'   chosen solver subject to optional nonnegativity or box constraints on the
#'   coefficients.
#'
#' @param X A numeric matrix or sparse matrix of predictors (design matrix).
#' @param y A numeric vector of responses.
#' @param lambdas Numeric value or vector specifying the ridge penalty
#'   parameter(s).
#' @param weights Optional numeric vector of observation weights. Default is
#'   \code{NULL}.
#' @param lower Numeric vector specifying lower bounds on the coefficients.
#'   Default is a vector of \code{-Inf}.
#' @param upper Numeric vector specifying upper bounds on the coefficients.
#'   Default is a vector of \code{Inf}.
#' @param nonnegative Logical; if \code{TRUE}, nonnegativity constraints are
#'   imposed on the coefficients (equivalent to setting \code{lower = 0}).
#'   Default is \code{FALSE}.
#' @param scaling Numeric vector specifying scaling factors for the columns of
#'   \code{X}. Default is a vector of ones (no scaling). This allows scaling of
#'   columns of \code{X}, e.g., by their L2 norm.
#' @param prior.mean Numeric vector specifying prior means for Gaussian priors
#'   implied by the ridge penalties. Default is a vector of zeros (i.e. zero
#'   centered means) to shrink to zero. Nonzero values will result in a targeted
#'   nonzero-centered ridge regression being used instead.
#' @param solver Character string specifying which solver to use. Options are
#'   \code{"eigen"}, \code{"bigGlm"} (or legacy alias \code{"glmnet"}),
#'   \code{"osqp"}. Default is \code{"eigen"}.
#' @param method Integer code specifying the method to be used within the
#'   solver. Default is \code{1L}, i.e. Cholesky LLT.
#' @param start Numeric vector of starting values for the coefficients. Default
#'   is a vector of zeros.
#' @param iteration Integer specifying the iteration number, used internally for
#'   iterative algorithms. Default is \code{1}.
#' @param control.solver List of control parameters for the solver. Default is
#'   generated by \code{control.solver.gen(solver = solver, method = method)}.
#' @param verbose Logical; if \code{TRUE}, additional information is printed
#'   during computation. Default is \code{FALSE}.
#'
#' @return A numeric vector of estimated coefficients.
#'
#' @details The \code{lmridge} function fits a ridge regression model of the
#' form: \deqn{\beta = \arg \min_{\beta} \left\{ \frac{1}{2} \| W^{1/2}(y - X \beta)
#' \|_2^2 + \frac{1}{2}\sum_j \lambda_j (\beta_j - \mu_j)^2 \right\}} where
#'   \eqn{W} contains the observation weights, \eqn{\lambda_j} are the ridge
#'   penalty parameters, and \eqn{\mu} is the prior mean of the coefficients
#'   (specified by \code{prior.mean}).
#'
#'   The function supports optional bounds on the coefficients via the
#'   \code{lower} and \code{upper} parameters and can impose nonnegativity
#'   constraints if \code{nonnegative = TRUE}.
#'
#'   The \code{scaling} parameter allows scaling of the predictors. If scaling
#'   is applied, the coefficients are rescaled back to the original scale before
#'   being returned.
#'
#'   Different solvers can be specified via the \code{solver} parameter:
#' \describe{
#'   \item{\code{"eigen"}}{Uses the \code{Eigen} package to solve the ridge
#'   regression problem using one of several solvers (see \code{method} option).}
#'   \item{\code{"bigGlm"}}{Uses the \code{bigGlm} function in the \code{\link[glmnet]{glmnet}} package to solve the ridge regression problem. \code{"glmnet"} is accepted as a legacy alias.}
#'   \item{\code{"osqp"}}{Uses the \code{\link[osqp]{osqp}} package (Operator Splitting Quadratic Program solver) to solve the problem with constraints. Most appropriate when box or nonnegativity constraints are applied.}
#' }
#'
#'   The \code{method} parameter specifies the specific method to be used when
#'   the \code{"eigen"} solver is used (1=Cholesky LLT, 2=Cholesky LDLT,
#'   3=CG with incomplete Cholesky preconditioning for sparse systems or
#'   diagonal preconditioning for dense systems, 4=LSCG with diagonal
#'   least-squares preconditioner, 5=column-pivoted QR, 6=BDCSVD for dense
#'   systems or Jacobi SVD for sparse systems).
#'
#'   LSCG uses Eigen's diagonal least-squares preconditioner without additional
#'   external column equilibration. A finite approximate LSCG solution is
#'   retained with a warning if the requested tolerance is not reached; a
#'   missing or nonfinite solution triggers the Cholesky fallback. OSQP uses
#'   the original coefficient coordinates and reports a warning when its
#'   requested accuracy is not reached. On a failed OSQP setup or solve,
#'   an infeasible/nonconvex status, or an invalid returned coefficient vector,
#'   a warning is issued and the previous IRLS coefficients (clipped to the
#'   bounds) are retained. Such a warning does not establish convergence.
#'   Finite-tolerance solutions can change the subsequent adaptive ridge
#'   selection path.
#'
#'   Eligible wide Eigen ridge systems use the Woodbury identity to solve an
#'   observation-space system of dimension \code{n}, rather than a predictor-space
#'   system of dimension \code{p}. The requested Eigen method is retained.
#'   Dense and sparse designs retain their storage type; optional row augmentation
#'   constructs a sparse augmented matrix. Eigen's SVD requires a dense factorization
#'   internally even when its input is sparse. OSQP requires sparse arrays at
#'   its solver boundary.
#'
#' @seealso \code{\link[glmnet]{glmnet}}, \code{\link[osqp]{osqp}},
#' \code{\link{control.solver.gen}}
#'
#' @example examples/lmridge.R
#' @export
#' @author Tom Wenseleers \email{tom.wenseleers@kuleuven.be} \\ Laboratory of
#' Socioecology and Social Evolution, KU Leuven \\
#' \url{https://bio.kuleuven.be/eeb/tw/research} \\ ORCID:
#' \href{https://orcid.org/0000-0002-1434-861X}{0000-0002-1434-861X}
lmridge <- function(X, y, 
                    lambdas = rep(0, ncol(X)),
                    weights = NULL,
                    nonnegative = FALSE,
                    lower = if (nonnegative) { rep(0,ncol(X)) } else { rep(-.Machine$double.xmax,ncol(X)) },
                    upper = rep(.Machine$double.xmax,ncol(X)),
                    scaling = rep(1, ncol(X)), # to allow scaling of columns of X, eg by L2 norm
                    prior.mean = NULL,
                    solver = "eigen",
                    method = 1L,
                    start = rep(0, ncol(X)),
                    iteration = 1, # IRLS iteration - passing this as extra info
                    control.solver = do.call("control.solver.gen", list(solver = solver, method = method)),
                    verbose = FALSE){
  
  # If nonnegative is true and no lower bound is provided, or the lower bound is larger than 0, it is clipped to 0
  if(nonnegative) lower[lower < 0] <- 0
  Xw <- Xweights(X, weights)
  yw <- Yweights(y, weights)
  # if (!issparse(Xw)) { Xw = as.matrix(Xw) }
  yw[is.nan(yw)] <- 0
  
  if(is.null(prior.mean)){
    prior.mean = rep(0, ncol(X))
  } else if (length(as.vector(prior.mean)) == 1){
    prior.mean = rep(prior.mean, ncol(X))
  } else if (length(as.vector(prior.mean)) != ncol(X)) {
    stop("Prior.mean needs to be a vector of length p or a numerical.")
  }
  if (length(scaling) != ncol(X) || any(!is.finite(scaling) | scaling <= 0))
    stop("scaling must contain one finite positive value per column of X.", call. = FALSE)
  scaled <- any(scaling != 1)
  if (scaled) {
    # theta = S beta: preserve the original quadratic objective and constraints.
    Xw <- Xw %*% Matrix::Diagonal(x = 1 / scaling)
    start <- start * scaling
    lambdas <- lambdas / scaling^2
    prior.mean <- prior.mean * scaling
    lower[lower <= -.Machine$double.xmax] <- -Inf
    upper[upper >= .Machine$double.xmax] <- Inf
    lower <- lower * scaling
    upper <- upper * scaling
  }
  
  if (solver == "osqp") {
    coefs <- lmridge.osqp(Xw = Xw, yw = yw, lambdas = lambdas, start = start, 
                          prior.mean = prior.mean, 
                          lower = lower, upper = upper, 
                          control.solver = control.solver,
                          iteration = iteration)
    
  } else if (solver %in% c("bigGlm", "bigglm", "glmnet")) {
    coefs <- lmridge.glmnet(Xw = Xw, yw = yw, lambdas = lambdas, 
                            lower = lower, upper = upper, 
                            control.solver = control.solver,
                            prior.mean = prior.mean,
                            iteration = iteration)
    
    } else if (solver == "eigen") {
    coefs <- lmridge.eigen(Xw = Xw, yw = yw, 
                             lambdas = lambdas, 
                           start = start, prior.mean = prior.mean,
                           lower = lower, upper = upper, 
                           control.solver = control.solver,
                           verbose = verbose,
                           iteration = iteration)
    
  } else {
    stop("Invalid solver choice") }
  
  # rescale coefficients to original scale
  if (scaled) coefs <- coefs / scaling
  
  if (sum(is.na(coefs))==length(coefs)) { warning("Ridge solver failed, returning starting coefficients.")
                                          return(if (scaled) start / scaling else start) }
  
  return(coefs)
}



lmridge.osqp <- function(Xw, 
                         yw, 
                         lambdas = rep(0, ncol(Xw)), 
                         lower, upper, start, 
                         control.solver = do.call("control.solver.gen", list(solver = "osqp")), 
                         prior.mean = NULL,
                         iteration = 1){
  if (!inherits(Xw, "dgCMatrix")) {
    Xw = as(Matrix(Xw, sparse = TRUE), "generalMatrix") # here always coercing Xw to sparse format
    # Xw <- Matrix(Xw, sparse = TRUE)
  } 
  
  if((sum(lambdas)!=0)) {
    Xwaug <- row_augX(Xw, lambdas)
    ywaug <- augY(yw, ncol(Xwaug), lambdas = lambdas, prior.mean = prior.mean) 
  } else {
    Xwaug <- Xw
    ywaug <- yw
  }
  
  # Keep the historical coefficient coordinates. Additional external
  # equilibration changes the finite-tolerance OSQP path and L0 selection.
  XtX <- crossprod(Xwaug)
  Xty <- as.numeric(crossprod(Xwaug, ywaug))

  # Obtain settings and create model
  settings <- osqp_settings_from_control(control.solver, start)
  
  if(is.null(start)) start <- rep(0, ncol(Xw))
  solution <- tryCatch({
    model <- osqp::osqp(P = XtX, q = -Xty,
                       A = .sparseDiagonal(ncol(Xw)),
                       l = lower, u = upper, pars = settings)
    if (inherits(model, "S7_object")) {
      model@WarmStart(x = start)
      model@Solve()
    } else {
      model$WarmStart(x = start)
      model$Solve()
    }
  }, error = function(e) e)
  if (inherits(solution, "error")) {
    return(osqp_previous_coefficients(conditionMessage(solution), start,
                                       lower, upper, iteration))
  }
  osqp_coefficients(solution, start, lower, upper, iteration)
}

osqp_previous_coefficients <- function(reason, start, lower, upper, iteration) {
  warning(sprintf(paste0("OSQP failed in IRLS iteration %s: %s; ",
                         "retaining previous coefficients within bounds."),
                  iteration, reason), call. = FALSE)
  clamp(as.numeric(start), lower, upper)
}

osqp_coefficients <- function(solution, start, lower, upper, iteration) {
  status <- solution$info$status
  if (is.null(status) || length(status) != 1L || is.na(status)) status <- "unknown status"
  status <- tolower(status)
  invalid <- !is.numeric(solution$x) || length(solution$x) != length(start) ||
    any(!is.finite(solution$x))
  # Failed solves can return finite placeholder values; these are not iterates.
  if (grepl("infeasible|non[ -]?convex|unsolved|unknown status", status) || invalid) {
    reason <- if (invalid) paste0(status, " (invalid coefficient vector)") else status
    return(osqp_previous_coefficients(reason, start, lower, upper, iteration))
  }
  if (!identical(status, "solved")) {
    warning(sprintf("OSQP did not converge to the requested accuracy in IRLS iteration %s: %s",
                    iteration, status), call. = FALSE)
  }
  clamp(solution$x, lower, upper)
}

osqp_settings_from_control <- function(control.solver, start = NULL) {
  args <- control.solver
  args$rowaug <- NULL
  osqp_args <- names(formals(osqp::osqpSettings))
  
  default_linsys_solver <- tryCatch(
    eval(formals(osqp::osqpSettings)$linsys_solver,
         envir = environment(osqp::osqpSettings)),
    error = function(e) NULL
  )
  if ("linsys_solver" %in% names(args) &&
      identical(unname(args$linsys_solver), 0L) &&
      identical(unname(default_linsys_solver), 1L)) {
    args$linsys_solver <- default_linsys_solver
  }
  
  if ("polishing" %in% osqp_args && "polish" %in% names(args)) {
    args$polishing <- args$polish
    args$polish <- NULL
  } else if ("polish" %in% osqp_args && "polishing" %in% names(args)) {
    args$polish <- args$polishing
    args$polishing <- NULL
  }
  
  warm_start_name <- if ("warm_starting" %in% osqp_args) "warm_starting" else "warm_start"
  args$warm_start <- NULL
  args$warm_starting <- NULL
  args[[warm_start_name]] <- !is.null(start) && any(start != 0)
  
  args <- args[names(args) %in% osqp_args]
  do.call(osqp::osqpSettings, args)
}


lmridge.glmnet <- function(Xw, yw, 
                           lambdas = rep(0, ncol(Xw)), 
                           lower, upper, 
                           control.solver = do.call("control.solver.gen", list(solver = "bigGlm")), 
                           prior.mean = NULL,
                           iteration = 1){
  if (is.null(prior.mean)) prior.mean <- rep(0, ncol(Xw))

  # Use row augmentation plus unpenalized bigGlm so zero- and nonzero-centered
  # ridge penalties share the same algebra as the Eigen and OSQP branches.
  # Use a path to reach the unpenalized solution only when the augmented system
  # may still be underdetermined. With positive ridge on every coefficient,
  # row augmentation makes the system tall and full rank even if original p > n.
  if ((is.null(lambdas) || any(lambdas <= 0)) && ncol(Xw) >= nrow(Xw)) {
    path = TRUE
  } else {
    path = FALSE
  }

   # Obtain Xwaug and ywaug
  if ((sum(lambdas) != 0)) {
    Xwaug <- row_augX(Xw, lambdas)
    ywaug <- augY(yw, ncol(Xwaug),
                  lambdas = lambdas,
                  prior.mean = prior.mean)
  } else {
    Xwaug <- Xw
    ywaug <- yw
  }
  glmnet_control <- list(
    thresh = control.solver$thresh,
    maxit = control.solver$maxit
  )
  glmnet_control <- glmnet_control[!vapply(glmnet_control, is.null, logical(1))]
  bigglm_args <- list(
    x = Xwaug,
    y = ywaug,
    intercept = FALSE,
    standardize = control.solver$standardize,
    standardize.response = TRUE,
    lower.limits = c(lower, -Inf),
    upper.limits = c(upper, Inf),
    family = "gaussian",
    path = path,
    control = glmnet_control
  )
  bigglm_args <- bigglm_args[!vapply(bigglm_args, is.null, logical(1))]
  model <- do.call(glmnet::bigGlm, bigglm_args)
  coefs <- coef(model)[-1]

  # apply box constraints in case coefs would slightly fall outside bounds
  coefs <- clamp(coefs, lower, upper) 
  return(coefs)
}


lscg_coefficients <- function(solution, iteration) {
  coefs <- solution$coefficients
  if (is.null(coefs) || any(!is.finite(coefs))) return(NULL)
  if (!isTRUE(solution$status)) {
    warning(sprintf(paste0("LSCG did not converge to the requested accuracy in IRLS iteration %s; ",
                           "using its finite approximate solution."), iteration), call. = FALSE)
  }
  as.vector(coefs)
}

eigen_ridge_solve <- function(A, b, start, control, iteration) {
  sparse <- issparse(A)
  A <- if (sparse) as(as(A, "generalMatrix"), "CsparseMatrix") else as.matrix(A)
  b <- as.matrix(b)
  method <- control$method
  solution <- switch(method,
    chol = if (sparse) solve_sparse_chol(A, b, pivot = control$pivot,
                                        ordering = control$ordering) else
      solve_dense_chol(A, b, pivot = control$pivot),
    QR = if (sparse) solve_sparse_QR(A, b, ordering = control$ordering) else
      solve_dense_QR(A, b, pivot = control$pivot),
    LSCG = if (sparse) solve_sparse_LSCG(A, b, as.matrix(start),
                                       tol = control$tol, maxit = control$maxit,
                                       precond = control$precond) else
      solve_dense_LSCG(A, b, as.matrix(start), tol = control$tol,
                      maxit = control$maxit, precond = control$precond),
    CG = if (sparse) solve_sparse_CG(A, b, as.matrix(start),
                                   tol = control$tol, maxit = control$maxit,
                                   precond = control$precond) else
      solve_dense_CG(A, b, as.matrix(start), tol = control$tol,
                    maxit = control$maxit, precond = control$precond),
    SVD = if (sparse) solve_sparse_SVD(A, b, svd = control$sparse.svd,
                                     precond = control$precond,
                                     threshold = control$threshold) else
      solve_dense_SVD(A, b, svd = control$svd, precond = control$precond,
                      threshold = control$threshold),
    stop("Invalid method."))
  if (method == "LSCG") return(lscg_coefficients(solution, iteration))
  coefs <- solution$coefficients
  if (is.null(coefs) || any(!is.finite(coefs))) return(NULL)
  if (method == "CG" && !isTRUE(solution$status)) {
    warning(sprintf(paste0("CG did not converge to the requested accuracy in IRLS iteration %s; ",
                           "using its finite approximate solution."), iteration), call. = FALSE)
  }
  as.numeric(coefs)
}

eigen_ridge_dual <- function(Xw, yw, lambdas, prior.mean, control, iteration) {
  n <- nrow(Xw); p <- ncol(Xw)
  penalized <- any(lambdas > 0)
  free <- if (penalized) which(lambdas == 0) else integer()
  invsqrt <- if (penalized) ifelse(lambdas > 0, 1 / sqrt(lambdas), 0) else rep(1, p)
  center <- if (penalized) prior.mean else rep(0, p)
  center[free] <- 0
  Z <- Xw %*% Matrix::Diagonal(x = invsqrt)
  A <- Matrix::tcrossprod(Z)
  if (penalized) diag(A) <- diag(A) + 1
  U <- Xw[, free, drop = FALSE]
  rhs <- cbind(as.numeric(yw - Xw %*% center), as.matrix(U))
  solution <- eigen_ridge_solve(A, rhs, matrix(0, n, ncol(rhs)), control, iteration)
  if (is.null(solution)) return(NULL)
  solution <- matrix(solution, n, ncol(rhs))
  u <- solution[, 1L]
  alpha <- numeric()
  if (length(free)) {
    T <- solution[, -1L, drop = FALSE]
    G <- as.matrix(Matrix::crossprod(U, T))
    alpha <- as.numeric(qr.coef(qr(G), as.numeric(Matrix::crossprod(U, u))))
    alpha[is.na(alpha)] <- 0
    u <- u - as.numeric(T %*% alpha)
  }
  beta <- center + invsqrt * as.numeric(Matrix::crossprod(Z, u))
  beta[free] <- alpha
  beta
}

lmridge.eigen <- function(Xw, yw, lambdas = rep(0, ncol(Xw)),
                          lower = rep(-.Machine$double.xmax, ncol(Xw)),
                          upper = rep(.Machine$double.xmax, ncol(Xw)),
                          start = rep(0, ncol(Xw)),
                          control.solver = control.solver.gen("eigen", 1L),
                          prior.mean = rep(0, ncol(Xw)), verbose = FALSE,
                          iteration = 1) {
  if (identical(control.solver$method, "chol") &&
      is.null(control.solver$ordering)) {
    control.solver$ordering <- as.integer(isTRUE(control.solver$NaturalOrdering))
  }
  p <- ncol(Xw)
  n <- nrow(Xw)
  if (is.null(start)) start <- rep(0, p)
  Xw <- if (issparse(Xw)) as(Xw, "generalMatrix") else as.matrix(Xw)
  # Positive diagonal penalties admit an n by n Woodbury system as soon as p > n.
  # With no penalty this is the minimum-norm observation-space least-squares solve.
  dual <- p > n && all(lambdas >= 0) &&
    (all(lambdas == 0) || sum(lambdas == 0) <= n)
  if (dual) {
    coefs <- eigen_ridge_dual(Xw, yw, lambdas, prior.mean, control.solver, iteration)
  } else {
    if (isTRUE(control.solver$rowaug) && any(lambdas != 0)) {
      A <- row_augX(Xw, lambdas)
      rhs <- augY(yw, p, prior.mean, lambdas)
    } else {
      A <- Xw
      rhs <- yw
    }
    # Rectangular QR, SVD and LSCG avoid squaring the condition number.
    rectangular <- isTRUE(control.solver$rowaug) &&
      control.solver$method %in% c("QR", "LSCG", "SVD")
    if (!rectangular) {
      if (isTRUE(control.solver$rowaug) && any(lambdas != 0)) {
        rhs <- Matrix::crossprod(A, rhs)
        A <- Matrix::crossprod(A)
      } else {
        rhs <- Matrix::crossprod(Xw, yw) + lambdas * prior.mean
        A <- Matrix::crossprod(Xw) + Matrix::Diagonal(x = lambdas)
      }
    }
    coefs <- eigen_ridge_solve(A, rhs, start, control.solver, iteration)
  }
  if (is.null(coefs) && control.solver$method != "chol") {
    warning(sprintf("eigen %s solver failed in IRLS iteration %s, trying Cholesky LLT solver as fallback.",
                    control.solver$method, iteration), call. = FALSE)
    return(lmridge.eigen(Xw, yw, lambdas, lower, upper, start,
                        control.solver.gen("eigen", 1L), prior.mean, verbose, iteration))
  }
  if (is.null(coefs)) {
    warning(sprintf("Eigen Cholesky failed in IRLS iteration %s; retaining previous coefficients.",
                    iteration), call. = FALSE)
    coefs <- start
  }
  clamp(coefs, lower, upper)
}


Xweights <- function (X, weights)
{
  ## ---- fast exit : no weighting required --------------------------------
  if (is.null(weights))                return(X)
  
  ## coerce *once* to a plain numeric vector
  if (is.matrix(weights) || inherits(weights, "Matrix"))
    weights <- as.numeric(weights[, 1L])
  
  ## all weights equal to one   - avoid all.equal() for sparse objects -----
  if (length(weights) == 1L) {
    if (weights == 1)               return(X)
  } else {
    ## every entry really equal to 1 ?
    if (all(weights == 1))          return(X)
  }
  
  ## ---- real weighting ----------------------------------------------------
  w_sqrt <- sqrt(weights)
  
  if (issparse(X) || inherits(X, "Matrix")) {
    ## left-multiply by diagonal - keeps sparsity
    return( Matrix::Diagonal(x = w_sqrt) %*% X )
  }
  
  ## dense fallback
  sweep(X, 1L, w_sqrt, `*`)
}


Yweights <- function(y, weights){
  if (!is.null(weights)) {
    return(y * sqrt(weights))
  } else {
    return(y)
  }
}




# UTILITY FUNCTIONS ####

should_augment <- function(lambdas) {
  !is.null(lambdas) && any(lambdas != 0)      # TRUE <=> at least one real penalty
}

# Row augmentation of the covariate matrix if lambda!=0 to add ridge penalty
# Ref :
# https://stats.stackexchange.com/a/164546/27340
# https://stats.stackexchange.com/a/203699/27340
row_augX <- function(Xw, lambdas = NULL){
  if (length(lambdas)==0) lambdas = NULL
  if (should_augment(lambdas)) {
    if (issparse(Xw)) { return( as(Matrix(rbind(Xw, Diagonal(x=sqrt(lambdas))), sparse=T), "generalMatrix") ) } else {
                        return( rbind2(as(Matrix(Xw, sparse=T), "generalMatrix"), Diagonal(x = sqrt(lambdas))) # always returning augmented matrix as sparse dgCMatrix if row augmentation method is requested
                        # return( rbind(Xw, diag(x=sqrt(lambdas)))
                        )
                        }
    } else
    { return(Xw) }

}

# augment y
augY <- function(yw, p, prior.mean = NULL, lambdas = NULL){
  if (length(lambdas)==0) lambdas=NULL
  if (should_augment(lambdas)) {
    if(is.null(prior.mean) | is.null(lambdas) | !isTRUE(any(prior.mean != 0))){
      return(c(yw, rep(0, p))) # zero centered row augmentation
    } else {
      return(c(yw, as.numeric(prior.mean) * sqrt(lambdas)))  # nonzero centered row augmentation
    } } else { return(yw) }
}


