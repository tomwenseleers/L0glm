# Single-channel Poisson deconvolution: shifted copies of a known PSF.
single <- simul(method=2, n=500, p=500, s=.1, seed=2)
fit_single <- L0glm.fit(single$X, single$y, family=poisson(identity),
  lambda="gic", nonnegative=TRUE, relaxed=TRUE, parallelize=FALSE)
L0glm.metrics(fit_single, beta_true=single$beta_true)[
  c("gic", "TP", "FP", "FN", "TN", "F1_score", "MCC")]

old_par <- par(no.readonly=TRUE)
par(mfrow=c(1, 1), mgp=c(2, .7, 0))
# The default PSF has peak one. Scale both spike trains by the same PSF peak
# to display them in signal units; negative values indicate mirroring only.
spike_scale <- max(single$X)
beta_single <- as.numeric(coef(fit_single))
mu_single <- as.numeric(fitted(fit_single))
height <- max(as.numeric(single$y), as.numeric(single$y_true), mu_single,
  as.numeric(single$beta_true)*spike_scale, beta_single*spike_scale)
plot(single$x, single$y, type="l", col="grey65", ylim=c(-1, 1)*height*1.15,
  xlab="Time", ylab="Signal / spike height (fit mirrored)",
  main="Single-channel Poisson deconvolution")
abline(h=0, col="grey75", lty=3)
lines(single$x, single$y_true, col="grey30", lty=2)
segments(single$x_beta, 0, single$x_beta,
  as.numeric(single$beta_true)*spike_scale, col="navy")
lines(single$x, -mu_single, col="orange", lwd=1.5)
segments(single$x_beta, 0, single$x_beta, -beta_single*spike_scale, col="red")
legend("topright", c("Observed signal", "True signal", "True spikes",
  "Fitted signal (mirrored)", "Fitted spikes (mirrored)"),
  col=c("grey65", "grey30", "navy", "orange", "red"),
  lty=c(1, 2, 1, 1, 1), bty="n", cex=.75)

# Multichannel Poisson deconvolution: select rows shared across channels.
# Retain every mass channel generated by the simulation.
multi <- simul(method=4, n=500, p=500, s=.05, seed=2)
fit_multi <- L0glm.fit(multi$X, multi$y, family=poisson(identity),
  lambda="gic", nonnegative=TRUE, grouped=TRUE, relaxed=TRUE,
  parallelize=FALSE)
L0glm.metrics(fit_multi, beta_true=multi$beta_true)[
  c("gic", "TP", "FP", "FN", "TN", "F1_score", "MCC",
    "within_row_F1_score", "within_row_MCC")]
# The within-row scores assess channel sparsity among correctly recovered rows.
dim(coef(fit_multi))                  # original predictors by response channels
par(mfrow=c(2, 1))
plotmat(multi$beta_true, xlab="Spike location", ylab="Channel",
  main="True multichannel coefficients")
plotmat(coef(fit_multi), xlab="Spike location", ylab="Channel",
  main="Estimated multichannel coefficients")
par(old_par)

# Precluster into at most 32 channel groups, select on their summed counts,
# then refine and return coefficients for every original mass channel.
system.time(fit_multi_clustered <- L0glm.fit(multi$X, multi$y,
  family=poisson(identity), lambda="gic", nonnegative=TRUE,
  grouped=TRUE, relaxed=TRUE, parallelize=TRUE, ncores=4L,
  precluster=TRUE, cluster.refit=TRUE,
  control.precluster=list(k.max=32L, rowbins=5L)))
fit_multi_clustered$preclustering$clusters
fit_multi_clustered$preclustering$seconds
L0glm.metrics(fit_multi_clustered, beta_true=multi$beta_true)[
  c("gic", "TP", "FP", "FN", "TN", "F1_score", "MCC",
    "within_row_F1_score", "within_row_MCC")]
dim(coef(fit_multi_clustered))         # all original predictors and channels

# A smooth nonnegative background: append a low-df spline basis and keep
# those columns unpenalized. Poisson backgrounds add directly to the signal.
B <- splines::bs(seq(0, 1, length.out=nrow(multi$X)), df=6, intercept=TRUE)
alpha <- outer(c(2, 5, 3, 7, 4, 2), seq(.5, 1.5, length.out=ncol(multi$y)))
set.seed(3)
Y_background <- multi$y + matrix(rpois(length(multi$y), B %*% alpha),
  nrow(multi$y), ncol(multi$y))
X_background <- cbind(multi$X, Matrix::Matrix(B, sparse=TRUE))
compulsory <- ncol(multi$X) + seq_len(ncol(B))
fit_background <- L0glm.fit(X_background, Y_background,
  family=poisson(identity), lambda="gic", nonnegative=TRUE,
  always.include=compulsory, grouped=TRUE, relaxed=TRUE,
  precluster=TRUE, ncores=4L,
  control.precluster=list(k.max=32L, rowbins=5L))
background_hat <- B %*% as.matrix(coef(fit_background)[compulsory, , drop=FALSE])
# Every original mass channel is retained in both the peak and background fit.
dim(coef(fit_background))
fit_background$nuisance$seconds
L0glm.metrics(fit_background,
  beta_true=rbind(multi$beta_true, Matrix::Matrix(alpha, sparse=TRUE)))[
  c("gic", "TP", "FP", "FN", "TN", "F1_score", "MCC",
    "within_row_F1_score", "within_row_MCC")]

